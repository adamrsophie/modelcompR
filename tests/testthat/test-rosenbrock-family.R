# The Rosenbrock methods of OrdinaryDiffEqRosenbrock 2.7.5 and the tableaus of
# OrdinaryDiffEqRosenbrockTableaus 2.4.2 (R/solvers-rosenbrock*.R) against
# reference runs printed by tools/rosenbrock-probe.jl: the number of saved
# points, nf, njacs, nw, nsolve, naccept and nreject must agree exactly, and
# the final state and the dense output values to rounding.

# long reference comparisons: run on CI (NOT_CRAN = true), not on CRAN
skip_on_cran()

rbf_rober <- function(u, p, t) c(-p[1] * u[1] + p[2] * u[2] * u[3],
                                 p[1] * u[1] - p[2] * u[2] * u[3] - p[3] * u[2] * u[2], p[3] * u[2] * u[2])
rbf_rjac <- function(u, p, t) matrix(c(-p[1], p[2] * u[3], p[2] * u[2],
                                       p[1], -p[2] * u[3] - 2 * p[3] * u[2], -p[2] * u[2],
                                       0, 2 * p[3] * u[2], 0), 3, 3, byrow = TRUE)
rbf_roberdae <- function(u, p, t) c(-p[1] * u[1] + p[2] * u[2] * u[3],
                                    p[1] * u[1] - p[2] * u[2] * u[3] - p[3] * u[2] * u[2], u[1] + u[2] + u[3] - 1)
rbf_rdjac <- function(u, p, t) matrix(c(-p[1], p[2] * u[3], p[2] * u[2],
                                        p[1], -p[2] * u[3] - 2 * p[3] * u[2], -p[2] * u[2],
                                        1, 1, 1), 3, 3, byrow = TRUE)
rbf_pf <- function(u, p, t) c(-50 * (u[1] - u[2] * u[2]) + t, -u[2] + 0.5 * u[1] * u[3],
                              -2 * u[3] + u[1] * u[1] * u[1] - 0.1 * t * t)
rbf_pjac <- function(u, p, t) matrix(c(-50, 100 * u[2], 0, 0.5 * u[3], -1, 0.5 * u[1], 3 * u[1] * u[1], 0, -2),
                                     3, 3, byrow = TRUE)
rbf_ptgrad <- function(u, p, t) c(1, 0, -0.2 * t)
rbf_df <- function(u, p, t) c(-u[1] + u[3], u[1] - 2 * u[2] + 0.1 * t, u[3] - u[2] * u[2] - 0.5 * u[1])
rbf_djac <- function(u, p, t) matrix(c(-1, 0, 1, 1, -2, 0, -0.5, -2 * u[2], 1), 3, 3, byrow = TRUE)
rbf_dtgrad <- function(u, p, t) c(0, 0.1, 0)
rbf_M3 <- diag(c(1, 1, 0))
rbf_P <- c(0.04, 1e4, 3e7)

rbf_solve <- function(nm, case) {
  prob_rob <- ODEProblem(ODEFunction(rbf_rober, jac_fn = rbf_rjac), c(1, 0, 0), c(0, 10), p = rbf_P)
  prob_robdae <- ODEProblem(ODEFunction(rbf_roberdae, jac_fn = rbf_rdjac, mass_matrix = rbf_M3), c(1, 0, 0),
                            c(0, 10), p = rbf_P)
  prob_p <- ODEProblem(ODEFunction(rbf_pf, jac_fn = rbf_pjac, tgrad_fn = rbf_ptgrad), c(1, 0.5, 0.2), c(0, 2))
  prob_pfd <- ODEProblem(rbf_pf, c(1, 0.5, 0.2), c(0, 2))
  prob_d <- ODEProblem(ODEFunction(rbf_df, jac_fn = rbf_djac, tgrad_fn = rbf_dtgrad, mass_matrix = rbf_M3),
                       c(1, 0.5, 0.75), c(0, 2))
  prob_dfd <- ODEProblem(ODEFunction(rbf_df, mass_matrix = rbf_M3), c(1, 0.5, 0.75), c(0, 2))
  halve <- DiscreteCallback(function(u, t, integ) t == 0.5, function(integ) integ$u <- integ$u * 0.5)
  lim <- function(u, integ, p, t) pmax(u, 0)
  alg <- function(...) get(nm)(...)
  ts <- c(0.123, 0.777, 1.5)
  switch(case,
    rob = list(solve(prob_rob, alg(), reltol = 1e-6, abstol = 1e-8), c(0.5, 7)),
    plain = list(solve(prob_p, alg(), reltol = 1e-5, abstol = 1e-7), ts),
    tstop = list(solve(prob_p, alg(), tstops = 0.37, reltol = 1e-5, abstol = 1e-7), ts),
    cb = list(solve(prob_p, alg(), tstops = 0.5, callback = halve, reltol = 1e-5, abstol = 1e-7), c(0.3, 0.7)),
    nodense = list(solve(prob_p, alg(), save_everystep = FALSE, reltol = 1e-5, abstol = 1e-7), NULL),
    saveat = list(solve(prob_p, alg(), saveat = 0.25, reltol = 1e-5, abstol = 1e-7), NULL),
    fd = list(solve(prob_pfd, alg(autodiff = AutoFiniteDiff()), reltol = 1e-5, abstol = 1e-7), ts),
    dae = list(solve(prob_d, alg(), reltol = 1e-5, abstol = 1e-7), ts),
    daefd = list(solve(prob_dfd, alg(autodiff = AutoFiniteDiff()), reltol = 1e-5, abstol = 1e-7), ts),
    robdae = list(solve(prob_robdae, alg(), reltol = 1e-6, abstol = 1e-8), c(0.5, 7)),
    fixed = if (nm == "RosenbrockW6S4OS") list(solve(prob_p, alg(), dt = 0.05), ts) else
      list(solve(prob_p, alg(), dt = 0.05, adaptive = FALSE), ts),
    fixeddae = if (nm == "RosenbrockW6S4OS") list(solve(prob_d, alg(), dt = 0.05), ts) else
      list(solve(prob_d, alg(), dt = 0.05, adaptive = FALSE), ts),
    fixedfd = list(solve(prob_pfd, alg(autodiff = AutoFiniteDiff()), dt = 0.05), ts),
    age3 = list(solve(prob_rob, ROS34PW2(max_jac_age = 3), reltol = 1e-6, abstol = 1e-8), NULL),
    gtol = list(solve(prob_rob, ROS34PW2(jac_reuse_gamma_tol = 0.5), reltol = 1e-6, abstol = 1e-8), NULL),
    age20 = list(solve(prob_rob, Rosenbrock23(max_jac_age = 20), reltol = 1e-6, abstol = 1e-8), NULL),
    lim = list(solve(prob_p, alg(step_limiter = lim), reltol = 1e-5, abstol = 1e-7), NULL),
    stop("unknown case ", case))
}


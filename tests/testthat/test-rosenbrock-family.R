test_that("HybridExplicitImplicitRK uses the tableau it is given", {
  prob <- ODEProblem(ODEFunction(rbf_df, mass_matrix = rbf_M3), c(1, 0.5, 0.75), c(0, 1))
  s1 <- solve(prob, Tsit5DA())
  tab <- modelcompR:::.ROSEN_TABLEAUS$Tsit5DATableau
  s2 <- solve(prob, HybridExplicitImplicitRK(tab, order = 5))
  expect_identical(s2$u, s1$u)
  expect_identical(s2$stats, s1$stats)
  # upstream builds the cache from tabtype(::HybridExplicitImplicitRK) =
  # Tsit5DATableau (rosenbrock_caches.jl:88) whatever tableau it is given
  tab2 <- tab
  tab2$bhat <- 2 * tab$bhat
  s4 <- solve(prob, HybridExplicitImplicitRK(tab2, order = 5))
  expect_false(identical(s4$stats, s1$stats))
  # the explicit Runge-Kutta method of the tableau without a mass matrix
  s3 <- solve(ODEProblem(function(u, p, t) -u, 1, c(0, 1)), Tsit5DA())
  expect_equal(s3$u[[length(s3$t)]], exp(-1), tolerance = 1e-6)
  expect_error(HybridExplicitImplicitRK(list(A = 1), order = 2), "tableau")
})


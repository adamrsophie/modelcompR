test_that("interpolations, clocks, aliasing, stats and traits", {
  f <- HermiteInterpolation(c(0, 1), rbind(0, 1), rbind(0, 2))
  expect_equal(f(0.5), 0.5^2, tolerance = 1e-12)
  expect_equal(LinearInterpolation(c(0, 2), rbind(c(0, 0), c(2, 4)))(1), c(1, 2))
  expect_equal(ConstantInterpolation(c(0, 1, 2), rbind(1, 2, 3))(1.5), 2)
  expect_equal(BasicInterpolation(c(0, 1), rbind(0, 1))(0.25), 0.25)
  expect_equal(RootfindOpt$LeftRootFind, LeftRootFind)
  expect_equal(alg_interpretation(EulerHeun()), AlgorithmInterpretation$Stratonovich)
  expect_equal(first_clock_tick_time(PeriodicClock(0.5), 0.2), 0.5)
  expect_true(iscontinuous(Continuous()) && iseventclock(EventClock("e")) && is_discrete_time_domain(Clock(1)))
  sol <- solve(ODEProblem(function(u, p, t) -u, 1, c(0, 1)), Tsit5(), saveat = 0.25)
  expect_equal(canonicalize_indexed_clock(IndexedClock(Continuous(), 2:3), sol), c(0.25, 0.5))
  expect_s3_class(ODEAliasSpecifier(alias_u0 = TRUE), "AliasSpecifier")
  expect_equal(DEStats(nf = 3L)$nf, 3L)
  expect_equal(numargs(function(u, p, t) u), 3L)
  expect_s3_class(TooFewArgumentsError(1), "TooFewArgumentsError")
  expect_equal(DEFAULT_OUTPUT_FUNC(1, 1), list(1, FALSE))
  expect_length(generate_sim_seeds(4, seed = 1), 4L)
  g <- UJacobianWrapper(function(u, p, t) -p * u, 0, 2)
  expect_equal(g(3), -6)
  expect_equal(ParamJacobianWrapper(function(u, p, t) p * u, 0, 2)(3), 6)
  expect_true(has_jac(ODEFunction(function(u, p, t) -u, jac_fn = function(u, p, t) -1)))
  expect_false(has_tgrad(ODEFunction(function(u, p, t) -u)))
  expect_true(requires_additive_noise(SOSRA()))
  expect_true(is_diagonal_noise(SDEProblem(function(u, p, t) u, function(u, p, t) u, 1, c(0, 1))))
  expect_equal(interp_summary(solve(ODEProblem(function(u, p, t) -u, 1, c(0, 1)), Tsit5())),
               "specialized order interpolation of Tsit5")
})

test_that("solution builders, errors, initialization and saved values", {
  af <- ODEFunction(function(u, p, t) -u, analytic = function(u0, p, t) u0 * exp(-t))
  sol <- solve(ODEProblem(af, 1, c(0, 1)), Tsit5(), reltol = 1e-8, abstol = 1e-10)
  er <- calculate_solution_errors(sol, dense_errors = TRUE)$errors
  expect_lt(er$final, 1e-7)
  expect_lt(er$L_inf, 1e-6)
  expect_true(has_analytic(af))
  bs <- build_solution(ODEProblem(function(u, p, t) 1, 0, c(0, 1)), Tsit5(), c(0, 1), rbind(0, 1))
  expect_equal(bs(0.5), 0.5)
  expect_equal(solution_new_retcode(bs, "MaxIters")$retcode, "MaxIters")
  expect_false(isTRUE(.sol_env(strip_interpolation(bs))$dense))
  # save_idxs keeps symbolic indexing
  p2 <- ODEProblem(function(u, p, t) -u, c(1, 2), c(0, 1))
  s2 <- solve(p2, Tsit5(), save_idxs = 2)
  expect_length(s2$u[[1]], 1L)
  expect_equal(get_saved_state_idxs(s2), 2L)
  # OverrideInitData for a problem of R functions
  ip <- NonlinearProblem(function(u, p) u^2 - 4, 1)
  pr <- ODEProblem(function(u, p, t) -u, 0, c(0, 1))
  pr$initialization_data <- OverrideInitData(ip, initializeprobmap = function(s) s$u)
  gv <- get_initial_values(pr)
  expect_true(gv$success)
  expect_equal(unname(gv$u0), 2, tolerance = 1e-8)
  expect_equal(promote_tspan(3), c(0, 3))
  expect_true(detect_cycles(list(c("a", "b"), c("b", "a"))))
  expect_false(detect_cycles(list(c("a", "b"), c("b", "c"))))
  expect_error(check_prob_alg_pairing(p2, EM()), "does not solve")
  expect_equal(problem_type(p2), "StandardODEProblem")
  integ <- init(p2, Tsit5())
  step_integrator(integ)
  set_ut(integ, c(1, 1), 0.5)
  expect_equal(integ$t, 0.5)
  integ$p <- 3
  save_discretes_if_enabled(integ)
  expect_equal(tail(integ$param_p, 1)[[1]], 3)
  expect_length(split_callbacks(CallbackSet(PresetTimeCallback(0.5, function(i) NULL)))$discrete, 1L)
})

test_that("algorithm traits and integrator utilities", {
  expect_equal(alg_order(SRIW1()), 1.5)
  expect_true(isadaptive(SOSRI()) && !isadaptive(EM()))
  expect_true(alg_needs_extra_process(SRIW1()))
  expect_equal(delta_default(SRIW1()), 1 / 6)
  expect_true(is_split_step(ISSEM()))
  gen <- SDEProblem(function(u, p, t) u, function(u, p, t) matrix(1, 1, 2), 1, c(0, 1), noise_rate_prototype = matrix(0, 1, 2))
  expect_false(alg_compatible(gen, SRIW1()))
  expect_true(supports_regular_jumps(SimpleTauLeaping()))
  expect_false(isinplace(function(u, p, t) u))
  prob <- ODEProblem(function(u, p, t) -u, c(1, 2), c(0, 1))
  integ <- init(prob, Tsit5(), tstops = 0.5)
  expect_equal(first_tstop(integ), 0.5)
  expect_true(has_tstop(integ))
  step_integrator(integ)
  t1 <- integ$t
  change_t_via_interpolation(integ, t1 / 2)
  expect_equal(integ$t, t1 / 2)
  expect_equal(integ$u, exp(-t1 / 2) * c(1, 2), tolerance = 1e-6)
  expect_s3_class(unwrap_alg(integ), "Tsit5")
  auto_dt_reset(integ)
  expect_gt(get_proposed_dt(integ), 0)
  # growing the state: the right-hand side follows the size of u
  grow <- ODEProblem(function(u, p, t) -u, 1, c(0, 1))
  ig <- init(grow, Tsit5())
  step_integrator(ig)
  addat(ig, 2, 5)
  sg <- solve_integrator(ig)
  expect_length(tail(sg$u, 1)[[1]], 2L)
  expect_warning(check_keywords(integ, c("abstol", "foo"), c("abstol")), "foo")
})

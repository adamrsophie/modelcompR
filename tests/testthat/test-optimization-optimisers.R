test_that("Optimisers rules reproduce Julia iterates", {
  for (i in seq_len(nrow(ref))) {
    r <- ref[i, ]
    args <- list(probs[[r[1]]], if (r[2] == "AdamNoBest") Adam(0.05) else rules[[r[2]]](), maxiters = as.integer(r[3]))
    if (r[2] == "AdamNoBest") args$save_best <- FALSE
    s <- suppressWarnings(do.call(solve, args))
    expect_equal(unname(s$u), as.numeric(r[4:5]), tolerance = 1e-13, label = paste(r[1:3], collapse = " "))
    expect_equal(s$objective, as.numeric(r[6]), tolerance = 1e-13, label = paste(r[1:3], collapse = " "))
    expect_identical(s$retcode, "Default")
  }
})

test_that("Optimisers solver options and aliases", {
  p <- probs$quad
  expect_error(solve(p, Adam()), "maxiters")
  expect_equal(Descent()$eta, 0.100000001490116119384765625)
  expect_identical(class(ADAM(0.1)), class(Adam(0.1)))
  expect_equal(ADAMW(0.1)$eta, 0.1)
  for (a in list(NADAM(), RADAM(), OADAM(), ADAGrad(), ADADelta())) expect_s3_class(a, "AbstractRule")
  expect_warning(solve(probs$rosen, Descent(), maxiters = 7), "Skipping parameter update")
  s <- solve(p, Adam(0.05), epochs = 10)
  expect_equal(s$stats$iterations, 10L)
  expect_true(requiresgradient(Adam()))
  st <- Optimisers$setup(Momentum(0.1), c(1, 2))
  up <- Optimisers$update(st, c(1, 2), c(1, 1), Momentum(0.1))
  expect_equal(up[[2]], c(0.9, 1.9))
})

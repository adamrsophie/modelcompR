# SciMLBase, DiffEqBase and StochasticDiffEqCore names reexported by
# StochasticDiffEq (R/scimlbase-reexports.R) and the nonlinear solver
# choices of OrdinaryDiffEqNonlinearSolve (R/stochastic-nlsolve.R). The
# DEVerbosity presets are those of DiffEqBase src/verbosity.jl.

test_that("solution constructors build the SciMLBase solution types", {
  prob <- ODEProblem(function(u, p, t) -u, 1, c(0, 1))
  W <- list(t = c(0, 0.5, 1), W = rbind(0, 0.1, 0.3))
  rs <- RODESolution(c(0, 0.5, 1), rbind(1, 0.6, 0.4), prob, W = W)
  expect_s3_class(rs, "RODESolution")
  expect_s3_class(rs, "ODESolution")
  expect_equal(rs(0.25), 0.8)
  expect_equal(rs$W$W[3, 1], 0.3)
  ds <- DAESolution(c(0, 1), rbind(1, 2), prob)
  expect_s3_class(ds, "DAESolution")
  expect_equal(ds(0.5), 1.5)
  np <- NonlinearProblem(function(u, p) u^2 - 2, 1)
  ns <- NonlinearSolution(np, list(name = "manual"), sqrt(2), resid = 0)
  expect_s3_class(ns, "NonlinearSolution")
  expect_equal(ns$u, sqrt(2))
  ss <- SteadyStateSolution(np, list(name = "manual"), 1.5)
  expect_s3_class(ss, c("SteadyStateSolution", "NonlinearSolution"))
  os <- OptimizationSolution(np, list(name = "manual"), c(1, 2), objective = 3)
  expect_s3_class(os, "OptimizationSolution")
  expect_equal(os$objective, 3)
  ls <- LinearSolution(c(1, 2))
  expect_equal(ls$u, c(1, 2))
  pt <- PDETimeSeriesSolution(rs, list(grid = 1:3))
  expect_s3_class(pt, c("PDETimeSeriesSolution", "PDESolution"))
  expect_equal(attr(pt, "disc_data")$grid, 1:3)
  expect_identical(attr(pt, "original_sol"), rs)
  expect_equal(pt(0.25), 0.8)
  expect_s3_class(PDENoTimeSolution(ns, NULL), "PDENoTimeSolution")
})

test_that("PDE problem wrapper and discretization generics", {
  base <- ODEProblem(function(u, p, t) -u, c(1, 2), c(0, 1))
  pp <- PDEProblem(base, space = list(x = c(0, 1)))
  expect_s3_class(pp, "PDEProblem")
  expect_identical(pp$prob, base)
  expect_error(discretize(NULL, structure(list(), class = "NoSuchGrid")), "no discretize\\(\\) method")
  expect_error(symbolic_discretize(NULL, list()), "no symbolic_discretize\\(\\) method")
  registerS3method("discretize", "TestGrid", function(sys, discretizer, ...) list(sys, ...),
                   envir = asNamespace("modelcompR"))
  expect_equal(discretize("s", structure(list(), class = "TestGrid"), 3), list("s", 3))
})

test_that("further problem and function types", {
  expect_error(ConvexOptimizationProblem(function(u, p) sum(u^2), c(1, 2), lb = c(0, 0)),
               "If any of `lb` or `ub` is provided, both must be provided.", fixed = TRUE)
  cp <- ConvexOptimizationProblem(function(u, p) sum(u^2), c(1, 2), lb = c(0, 0), ub = c(3, 3), sense = "MaxSense")
  expect_s3_class(cp, "ConvexOptimizationProblem")
  expect_equal(cp$sense, "MaxSense")
  expect_equal(cp$f$f(c(1, 2), NULL), 5)
  hf <- HomotopyNonlinearFunction(function(u, p) u^2 - 2)
  expect_s3_class(hf, c("HomotopyNonlinearFunction", "NonlinearFunction"))
  expect_equal(hf$f(2, NULL), 2)
  expect_identical(HomotopyNonlinearFunction(hf), hf)
  inf <- ODEInputFunction(function(x, u, p, t) -x + u, jac = function(x, u, p, t) -1)
  expect_s3_class(inf, "ODEInputFunction")
  expect_equal(inf$f(1, 0.5, NULL, 0), -0.5)
  expect_equal(inf$jac(1, 0.5, NULL, 0), -1)
})

test_that("ensemble context and test solution", {
  ctx <- EnsembleContext(3, 2, 1, 42)
  expect_equal(c(ctx$sim_id, ctx[["repeat"]], ctx$worker_id, ctx$sim_seed), c(3, 2, 1, 42))
  sim <- EnsembleSolution(list(1, 2), elapsed = 0.5, converged = FALSE)
  ts <- EnsembleTestSolution(sim, list(final = c(0.1, 0.2)), list(final = 0.05), list(final = 0.15),
                             list(final = 0.15))
  expect_s3_class(ts, c("EnsembleTestSolution", "EnsembleSolution"))
  expect_equal(ts$elapsed, 0.5)
  expect_false(ts$converged)
  expect_equal(ts$u, list(1, 2))
  expect_equal(ts$weak_errors$final, 0.05)
})

test_that("DEVerbosity presets match DiffEqBase", {
  v <- DEVerbosity()
  expect_length(v, 33L)
  expect_equal(v[["dense_output_saveat"]], "WarnLevel")
  expect_equal(v[["stage_limiter_unused"]], "ErrorLevel")
  expect_equal(v[["alg_switch"]], "Silent")
  expect_equal(attr(v, "linear_verbosity"), "Minimal")
  m <- DEVerbosity(preset = "Minimal")
  expect_equal(m[["dense_output_saveat"]], "Silent")
  expect_equal(m[["newton_convergence"]], "WarnLevel")
  expect_equal(m[["state_dependent_delay"]], "WarnLevel")
  d <- DEVerbosity(preset = "Detailed")
  expect_equal(d[["alg_switch"]], "InfoLevel")
  expect_equal(d[["step_rejected"]], "Silent")
  expect_equal(d[["mismatched_input_output_type"]], "WarnLevel")
  a <- DEVerbosity(preset = "All")
  expect_equal(a[["step_rejected"]], "InfoLevel")
  expect_equal(a[["mismatched_input_output_type"]], "InfoLevel")
  expect_equal(attr(a, "nonlinear_verbosity"), "All")
  expect_true(all(DEVerbosity(preset = FALSE) == "Silent"))
  expect_equal(DEVerbosity(alg_switch = "InfoLevel")[["alg_switch"]], "InfoLevel")
  expect_error(DEVerbosity(nope = "Silent"), "unknown verbosity toggle")
  expect_error(DEVerbosity(alg_switch = "Loud"), "unknown verbosity level")
})

test_that("SDE integrator pieces", {
  prob <- SDEProblem(function(u, p, t) -u, function(u, p, t) 0.1 * u, 1, c(0, 1))
  integ <- init(prob, SOSRI(), seed = 1)
  expect_true(inherits(integ, SDEIntegrator))
  expect_true(inherits(integ, "ODEIntegrator"))
  o <- SDEOptions(abstol = 1e-3)
  expect_s3_class(o, "SDEOptions")
  expect_equal(o$abstol, 1e-3)
  expect_equal(o$qmax, 9 / 8)
  s1 <- do.call(solve, c(list(prob, SOSRI()), o, seed = 1))
  s2 <- solve(prob, SOSRI(), abstol = 1e-3, seed = 1)
  expect_equal(s1$u, s2$u)
  expect_identical(concrete_prob(prob), prob)
  jp <- JumpProblem(DiscreteProblem(c(10), c(0, 1)), Direct(),
                    ConstantRateJump(function(u, p, t) 1, function(integ) integ$u[1] <- integ$u[1] - 1))
  expect_s3_class(concrete_prob(jp), "DiscreteProblem")
  expect_equal(names(alg_cache(Tsit5(), ODEProblem(function(u, p, t) -u, 1, c(0, 1)))), "fsal")
  expect_true(is.environment(alg_cache(ImplicitEM(), prob)))
  hits <- character()
  cb <- DiscreteCallback(function(u, t, integ) FALSE, function(integ) NULL,
                         initialize = function(integ) hits <<- c(hits, "init"),
                         finalize = function(integ) hits <<- c(hits, "final"))
  initialize_callback(CallbackSet(cb), integ$u, integ$t, integ)
  finalize(cb, integ$u, integ$t, integ)
  expect_equal(hits, c("init", "final"))
  expect_identical(addsteps(integ), integ)
})


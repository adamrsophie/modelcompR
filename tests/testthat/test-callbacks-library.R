test_that("saving, function calling and integrating callbacks", {
  prob <- ODEProblem(function(u, p, t) -u, c(1, 2), c(0, 1))
  sv <- SavedValues()
  s0 <- solve(prob, Tsit5())
  s1 <- solve(prob, Tsit5(), callback = SavingCallback(function(u, t, integ) sum(u), sv, saveat = 0.25))
  expect_equal(sv$t, seq(0, 1, by = 0.25))
  expect_equal(unlist(sv$saveval), 3 * exp(-sv$t), tolerance = 1e-5)
  # a callback that does not change the state keeps the steps
  expect_identical(s0$t, s1$t)
  sv2 <- SavedValues()
  solve(prob, Tsit5(), callback = SavingCallback(function(u, t, integ) u[1], sv2))
  expect_equal(sv2$t, s0$t)
  n <- 0
  solve(prob, Tsit5(), callback = FunctionCallingCallback(function(u, t, integ) n <<- n + 1, funcat = c(0.5, 0.75)))
  expect_equal(n, 3)
  iv <- IntegrandValuesSum()
  solve(prob, Tsit5(), callback = IntegratingSumCallback(function(u, t, integ) u, iv))
  expect_equal(iv$integrand, (1 - exp(-1)) * c(1, 2), tolerance = 1e-6)
  iv2 <- IntegrandValues()
  solve(prob, Tsit5(), callback = IntegratingGKCallback(function(u, t, integ) u[1]^2, iv2))
  expect_equal(sum(unlist(iv2$integrand)), (1 - exp(-2)) / 2, tolerance = 1e-6)
  expect_length(iv2$ts, length(s0$t) - 1L)
  ils <- IndependentlyLinearizedSolution(prob)
  solve(prob, Tsit5(), callback = LinearizingSavingCallback(ils))
  expect_equal(ils(0.5), exp(-0.5) * c(1, 2), tolerance = 1e-3)
  expect_gt(length(ils$ts[[1]]), length(s0$t))
})

test_that("domain, manifold, tolerance and termination callbacks", {
  # large steps of a fast decay undershoot zero
  fast <- ODEProblem(function(u, p, t) -50 * u, 1, c(0, 1))
  sp <- solve(fast, Tsit5(), reltol = 0.5, abstol = 0.5, callback = PositiveDomain(abstol = 1e-6))
  expect_gte(min(unlist(sp$u)), 0)
  ho <- ODEProblem(function(u, p, t) c(u[2], -u[1]), c(1, 0), c(0, 100))
  smp <- solve(ho, Tsit5(), reltol = 1e-3, abstol = 1e-3,
               callback = ManifoldProjection(function(u, p, t) sum(u^2) - 1))
  expect_lt(abs(sum(tail(smp$u, 1)[[1]]^2) - 1), 1e-12)
  gd <- solve(ho, Tsit5(), reltol = 1e-3, abstol = 1e-3,
              callback = GeneralDomain(function(u, p) sum(u^2) - 1))
  expect_lt(abs(sum(tail(gd$u, 1)[[1]]^2) - 1), 1e-12)
  ss <- solve(ODEProblem(function(u, p, t) -u, 1, c(0, 1e6)), Tsit5(), callback = TerminateSteadyState())
  expect_equal(ss$retcode, "Terminated")
  expect_lt(tail(ss$t, 1), 100)
  prob <- ODEProblem(function(u, p, t) -u, c(1, 2), c(0, 1))
  expect_lte(max(diff(solve(prob, Tsit5(), callback = StepsizeLimiter(function(u, p, t) 0.01))$t)), 0.009 + 1e-12)
  # the largest value after a step (AutoAbstol starts from abstol, not u0)
  i <- init(prob, Tsit5(), callback = AutoAbstol())
  sa <- solve_integrator(i)
  expect_equal(i$opts$abstol, max(abs(unlist(sa$u[-1]))) * 1e-3)
  set.seed(1)
  s <- solve(prob, Tsit5(), callback = ProbIntsUncertainty(0.2, 1))
  expect_false(isTRUE(all.equal(tail(s$u, 1)[[1]], exp(-1) * c(1, 2), tolerance = 1e-6)))
  expect_equal(solve(prob, Tsit5(), callback = AdaptiveProbIntsUncertainty(5))$retcode, "Success")
  hits <- numeric()
  it <- IterativeCallback(function(integ) if (integ$t < 0.7) integ$t + 0.3 else NULL,
                          function(integ) hits <<- c(hits, integ$t))
  solve(prob, Tsit5(), callback = it)
  expect_equal(hits, c(0.3, 0.6, 0.9))
})

test_that("variable rate aggregators and coupled jump problems", {
  vrj <- VariableRateJump(function(u, p, t) 1 + sin(t), function(integ) integ$u[1] <- integ$u[1] + 1)
  op <- ODEProblem(function(u, p, t) 0 * u, 0, c(0, 10))
  for (vra in list(VR_FRM(), VR_Direct(), VR_DirectFW())) {
    jp <- JumpProblem(op, Direct(), vrj, vr_aggregator = vra)
    v <- vapply(1:40, function(i) tail(solve(jp, Tsit5(), seed = i)$u, 1)[[1]], 0)
    expect_lt(abs(mean(v) - (11 - cos(10))), 4 * sqrt(11.84 / 40), label = vra$name)
  }
  expect_error(JumpProblem(op, Direct(), vrj, vr_aggregator = Direct()), "vr_aggregator")
  birth <- ConstantRateJump(function(u, p, t) 10, function(integ) integ$u[1] <- integ$u[1] + 1)
  death <- ConstantRateJump(function(u, p, t) u[1], function(integ) integ$u[1] <- integ$u[1] - 1)
  death2 <- ConstantRateJump(function(u, p, t) 1.1 * u[1], function(integ) integ$u[1] <- integ$u[1] - 1)
  j1 <- JumpProblem(DiscreteProblem(0, c(0, 5)), Direct(), birth, death)
  j2 <- JumpProblem(DiscreteProblem(0, c(0, 5)), Direct(), JumpSet(birth, death2))
  cp <- SplitCoupledJumpProblem(j1, j2, Direct(), list(c(1, 1), c(2, 2)))
  r <- t(vapply(1:60, function(i) tail(solve(cp, SSAStepper(), seed = i)$u, 1)[[1]], numeric(2)))
  expect_lt(abs(mean(r[, 1]) - 10 * (1 - exp(-5))), 4 * sqrt(10 / 60))
  expect_lt(abs(mean(r[, 2]) - 10 / 1.1 * (1 - exp(-5.5))), 4 * sqrt(9 / 60))
  # common random numbers: the difference has a small variance
  expect_lt(stats::var(r[, 1] - r[, 2]), 3)
  expect_equal(get_num_majumps(MassActionJump(c(1, 2), list(list(c(1, 1)), list(c(1, 1))),
                                              list(list(c(1, -1)), list(c(1, 1))))), 2L)
  expect_true(needs_depgraph(NRM()) && needs_vartojumps_map(RSSA()) && !needs_depgraph(Direct()))
  expect_equal(unclass(RateBounds(urate = 3)), list(lrate = 0, urate = 3, rateinterval = Inf))
  expect_identical(isolated_copy(j1), j1)
  expect_named(JumpDependencies(dep_graph = list(1L)), c("dep_graph", "vartojumps_map", "jumptovars_map"))
})

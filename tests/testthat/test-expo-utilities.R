eu_ref <- function(nm) .EU_REF[[nm]]
eu_close <- function(x, nm, tol = 1e-12) {
  j <- eu_ref(nm)
  expect_lt(max(abs(as.numeric(x) - j)) / max(1, abs(j)), tol, label = nm)
}


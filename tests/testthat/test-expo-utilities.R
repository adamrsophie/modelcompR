test_that("Arnoldi, Lanczos, expv and phiv match ExponentialUtilities", {
  expect_equal(.eu_arnoldi(eu_A15, eu_b15, m = 15)$m, eu_ref("arnm_A15_15_0"))
  eu_close(.eu_getH(.eu_arnoldi(eu_A15, eu_b15, m = 8, iop = 2)), "arnH_A15_8_2")
  eu_close(.eu_getH(.eu_arnoldi(eu_S15, eu_b15, m = 5)), "arnH_S15_5_0")
  for (nm in c("A15", "S15")) {
    M <- list(A15 = eu_A15, S15 = eu_S15)[[nm]]
    for (mi in list(c(5, 0), c(8, 2), c(15, 0))) {
      tag <- sprintf("%s_%d_%d", nm, mi[1], mi[2])
      eu_close(.eu_expv(0.3, M, eu_b15, m = mi[1], iop = mi[2]), paste0("expv_", tag))
      if (mi[1] == 15) next
      Ks <- .eu_arnoldi(M, eu_b15, m = mi[1], iop = mi[2])
      ph <- .eu_phiv_ks(0.3, Ks, 3)
      eu_close(ph$w, paste0("phiv_", tag))
      eu_close(ph$err, paste0("phiverr_", tag))
    }
  }
  eu_close(.eu_phiv_ks(0.3, .eu_arnoldi(eu_A15, eu_b15, m = 8, iop = 2), 2, correct = TRUE)$w, "phivc_A15_8_2")
  eu_close(.eu_phiv_ks(0.3, .eu_arnoldi(eu_S15, eu_b15, m = 5), 2, correct = TRUE)$w, "phivc_S15_5_0")
  # happy breakdown on an invariant subspace
  expect_equal(.eu_arnoldi(eu_A3, c(1, 0, 0), m = 3)$m, eu_ref("arnm_break"))
  eu_close(.eu_expv(0.5, eu_A3, c(1, 0, 0), m = 3), "expv_break")
})

test_that("phiv_timestep and expv_timestep match ExponentialUtilities", {
  B <- cbind(eu_b15, 0.5 * eu_b15, (1:eu_n) %% 3)

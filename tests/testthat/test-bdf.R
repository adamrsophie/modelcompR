test_that("QNDF with Julia's Newton failure retry reproduces OrdinaryDiffEqBDF", {
  # OrdinaryDiffEqBDF rescales the backward differences of the failed
  # attempt a second time
  local_mocked_bindings(.qndf_newton_fail = function(cache, dt, co) dt / co$failfactor)
  s <- solve(bdft_rprob, QNDF(), reltol = 1e-3, abstol = 1e-6)
  # the same steps and counts; over 1e5 time units the last bit differences
  # of the Newton corrections grow to a largest relative difference of
  # 1.1e-9 (u2 of the final state; 1.9e-10 with the fused norm) and 8.2e-11
  # in the dense values
  bdft_check(s, bdft_dae_ref[["QNDF rober"]], 1e-8)
  expect_equal(c(s(1e-3), s(0.5), s(4e4)), bdft_dae_dense_ref$QNDFrober, tolerance = 1e-8)
})


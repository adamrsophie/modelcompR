    .dabdf2_init = function(ctx, t, u) {
      cache <- bdft_init(ctx, t, u)
      cache$klast <- ctx$du
      cache
    },
    .dabdf2_step = function(ctx, t, u, dt, cache) {
      r <- bdft_step(ctx, t, u, dt, cache)
      if (!isTRUE(r$fail)) {
        r$k <- list(r$du, cache$klast, ctx$differential_vars)
        cache$klast <- r$du
      }
      r
    }
  )
  s <- solve(bdft_dprob, DABDF2(), reltol = 1e-4, abstol = 1e-6, initializealg = NoInit())
  expect_equal(c(s(0.3), s(0.77), s(1.51)), bdft_dae_dense_ref$DABDF2, tolerance = 1e-14)
})

test_that("QNDF retries a step after a Newton failure from the accepted history", {
  s <- solve(bdft_rprob, QNDF(), reltol = 1e-3, abstol = 1e-6)
  ref <- bdft_dae_ref[["QNDF rober"]]
  expect_equal(s$retcode, "Success")

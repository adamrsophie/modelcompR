bdft_sbdf_run <- function(key) {
  parts <- strsplit(key, " ", fixed = TRUE)[[1]]
  alg <- bdft_algs[[parts[1]]]()
  switch(parts[2],
    fixed = solve(bdft_sprob, alg, dt = 1 / 64),
    tstop = solve(bdft_sprob, alg, dt = 1 / 64, tstops = 0.1),
    cb = solve(bdft_sprob, alg, dt = 1 / 64, tstops = 0.1, callback = bdft_cb))
}

test_that("the SBDF family matches OrdinaryDiffEqBDF", {
  for (key in names(bdft_sbdf_ref)) {

# The methods of OrdinaryDiffEqBDF against Julia. Every reference number in
# this file is printed by tools/bdf-probe.jl (OrdinaryDiffEqBDF in the
# tools/julia environment). A reference row holds the number of saved
# points, nf, nf2, njacs, nw, nsolve, naccept, nreject and the final state.
#
# The QNDF family decides with exact comparisons of dt (dt != dtprev), so a
# one ulp change of a step can change the steps that follow. Julia's
# ODE_DEFAULT_NORM adds the squares by fused multiply adds, and its
# calculate_residuals and initial step fuse abstol + |u| reltol; R's
# .rms_norm, .err_norm and .initial_dt round each operation. That moves R's
# automatic first step of the heat problem by one ulp, so the QNDF runs pass
# Julia's first step as dt ("dt0" rows). QBDF at the lower tolerances and
# QNDF(max_order = 3) with the callback follow Julia only with the fused
# norm (Julia's own steps change when its first step moves by one ulp);
# they run once .rms_norm gives Julia's bits (bdft_julia_norm).

bdft_N <- 8
bdft_heat <- function(u, p, t) {
  l <- c(0, u[-bdft_N]); r <- c(u[-1], 0)
  p[1] * (l - 2 * u + r) * 81 - 0.5 * (u * u * u) + 0.1 * t
}
bdft_hjac <- function(u, p, t) {
  J <- matrix(0, bdft_N, bdft_N)
  for (i in seq_len(bdft_N)) {
    J[i, i] <- -2 * p[1] * 81 - 1.5 * (u[i] * u[i])
    if (i > 1) J[i, i - 1] <- p[1] * 81
    if (i < bdft_N) J[i, i + 1] <- p[1] * 81
  }
  J
}
bdft_f1 <- function(u, p, t) {
  l <- c(0, u[-bdft_N]); r <- c(u[-1], 0)
  p[1] * (l - 2 * u + r) * 81 - 0.5 * u * u * u
}
bdft_f2 <- function(u, p, t) p[2] * u * (1 - u) + 0.1 * t
bdft_u0 <- (seq_len(bdft_N) * (bdft_N + 1 - seq_len(bdft_N))) / 64
bdft_prob <- ODEProblem(ODEFunction(bdft_heat, jac_fn = bdft_hjac), bdft_u0, c(0, 0.3), c(1))
bdft_sprob <- SplitODEProblem(SplitFunction(bdft_f1, bdft_f2, jac = bdft_hjac), bdft_u0, c(0, 0.3), c(1, 5))
bdft_cb <- DiscreteCallback(function(u, t, integ) t == 0.1, function(integ) integ$u <- integ$u * 0.5)
# u1' = u2, 0 = u2^3 + u2 + u1^3 + u1 (so u2 = -u1 and u1 = exp(-t))
bdft_F <- function(du, u, p, t) c(du[1] - u[2], u[2] * u[2] * u[2] + u[2] + u[1] * u[1] * u[1] + u[1])
bdft_J <- function(du, u, p, gamma, t) matrix(c(gamma, 3 * (u[1] * u[1]) + 1, -1, 3 * (u[2] * u[2]) + 1), 2)
bdft_dprob <- DAEProblem(DAEFunction(bdft_F, jac = bdft_J), c(-1, -1), c(1, -1), c(0, 2),
                         differential_vars = c(TRUE, FALSE))
bdft_rober <- function(u, p, t) {
  c(-0.04 * u[1] + 1e4 * u[2] * u[3], 0.04 * u[1] - 1e4 * u[2] * u[3] - 3e7 * u[2] * u[2], 3e7 * u[2] * u[2])
}
bdft_rjac <- function(u, p, t) {
  matrix(c(-0.04, 0.04, 0, 1e4 * u[3], -1e4 * u[3] - 6e7 * u[2], 6e7 * u[2], 1e4 * u[2], -1e4 * u[2], 0), 3, 3)
}
bdft_rprob <- ODEProblem(ODEFunction(bdft_rober, jac_fn = bdft_rjac), c(1, 0, 0), c(0, 1e5))
# Julia's automatic first step of the heat problem (initdt lines of the
# probe), as hex literals: 1.3175590901772266e-9 and 1.3175590901772052e-12
bdft_dt_lo <- 0x1.6a2afa829f4a3p-30
bdft_dt_hi <- 0x1.72dc2356a72edp-40
# Julia's ODE_DEFAULT_NORM of a 2 vector (bits from DiffEqBase); R's plain
# sqrt(sum(x * x) / 2) is one ulp lower
bdft_julia_norm <- identical(.rms_norm(c(0x1.bc04776134755p-1, 0x1.a6bde0362e4d7p-1)), 0x1.b18296e7f60a5p-1)

bdft_stats <- function(s) {
  st <- s$stats
  c(length(s$t), st$nf, if (is.null(st$nf2)) 0L else st$nf2, st$njacs, st$nw, st$nsolve, st$naccept, st$nreject)
}
bdft_check <- function(s, ref, tol) {
  expect_equal(bdft_stats(s), ref[1:8])
  expect_equal(s$u[[length(s$u)]], ref[-(1:8)], tolerance = tol)
}

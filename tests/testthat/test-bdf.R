bdft_run <- function(key) {
  parts <- strsplit(key, " ", fixed = TRUE)[[1]]
  alg <- bdft_algs[[parts[1]]]()
  sc <- parts[2]
  hi <- sc %in% c("hi", "hi_dt0")
  rt <- if (hi) 1e-7 else 1e-4
  at <- if (hi) 1e-9 else 1e-6
  dt <- if (sc == "hi_dt0") bdft_dt_hi else if (grepl("_dt0", sc, fixed = TRUE)) bdft_dt_lo else NULL
  args <- list(bdft_prob, alg, reltol = rt, abstol = at)
  if (!is.null(dt)) args$dt <- dt
  if (sc %in% c("tstop", "cb", "tstop_dt0")) args$tstops <- 0.1
  if (sc == "cb") args$callback <- bdft_cb
  do.call(solve, args)
}


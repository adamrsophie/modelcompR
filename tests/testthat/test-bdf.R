test_that("DABDF2 and DNordsieckBDF match OrdinaryDiffEqBDF", {
  for (nm in c("DABDF2", "DNordsieckBDF")) {
    for (sc in c("lo", "hi")) {
      alg <- if (nm == "DABDF2") DABDF2() else DNordsieckBDF()
      rt <- if (sc == "hi") 1e-6 else 1e-4
      at <- if (sc == "hi") 1e-8 else 1e-6
      s <- solve(bdft_dprob, alg, reltol = rt, abstol = at, initializealg = NoInit())
      # DNordsieckBDF at the higher tolerances: the same steps and counts;
      # last bit differences of the corrections grow to about 1e-8
      bdft_check(s, bdft_dae_ref[[paste(nm, sc)]], if (nm == "DNordsieckBDF" && sc == "hi") 1e-7 else 1e-10)
      if (sc == "lo" && nm == "DNordsieckBDF")
        expect_equal(c(s(0.3), s(0.77), s(1.51)), bdft_dae_dense_ref$DNordsieckBDF, tolerance = 1e-12)
      if (sc == "lo" && nm == "DABDF2") {
        # the Hermite interpolant from du(t0) and du(t1) of each step
        v <- c(s(0.3)[1], s(0.77)[1], s(1.51)[1])
        expect_true(all(abs(v - exp(-c(0.3, 0.77, 1.51))) < 6e-4))
        expect_equal(c(s(0.3)[2], s(0.77)[2], s(1.51)[2]), bdft_dae_dense_ref$DABDF2[c(2, 4, 6)], tolerance = 1e-12)
      }
    }
  }
})


test_that("parallel ensembles give the serial law and per trajectory streams", {
  prob <- SDEProblem(function(u, p, t) -u, function(u, p, t) 0.5 + 0 * u, 1, c(0, 1))
  ens <- EnsembleProblem(prob)
  serial <- solve(ens, EM(), trajectories = 40, dt = 0.01, seed = 1)
  thr <- solve(ens, EM(), EnsembleThreads(cores = 2), trajectories = 40, dt = 0.01, seed = 1)
  thr1 <- solve(ens, EM(), EnsembleThreads(cores = 1), trajectories = 40, dt = 0.01, seed = 1)
  fin <- function(sim) vapply(seq_len(length(sim)), function(i) tail(sim[[i]]$u, 1)[[1]], 0)
  # the streams do not depend on the number of workers
  expect_equal(fin(thr), fin(thr1))
  expect_lt(abs(mean(fin(thr)) - exp(-1)), 4 * sqrt(0.25 / 2 * (1 - exp(-2)) / 40))
  expect_lt(abs(mean(fin(serial)) - mean(fin(thr))), 0.3)
  gk <- solve(ens, EM(), EnsembleGPUKernel(cores = 1), trajectories = 5, dt = 0.01, seed = 2)
  expect_length(gk, 5L)
  skip_on_cran()
  dist <- solve(ens, EM(), EnsembleDistributed(cores = 2), trajectories = 6, dt = 0.01, seed = 1)
  expect_equal(fin(dist), fin(solve(ens, EM(), EnsembleThreads(cores = 1), trajectories = 6, dt = 0.01, seed = 1)))
})

test_that("ensemble analysis follows SciMLBase's EnsembleAnalysis", {
  # componentwise_meanvar docstring
  mv <- componentwise_meanvar(list(c(1, 2), c(3, 4)))
  expect_equal(mv, list(mean = c(2, 3), var = c(2, 2)))
  expect_equal(componentwise_meanvar(list(c(1, 2), c(3, 4)), bessel = FALSE)$var, c(1, 1))
  expect_equal(componentwise_mean(list(c(1, 2), c(3, 4))), c(2, 3))
  mc <- componentwise_meancov(list(1, 2, 3), list(2, 4, 6))
  expect_equal(mc$cov, 2)
  expect_equal(componentwise_meancor(list(1, 2, 3), list(2, 4, 6))$cor, 1)
  wm <- componentwise_weighted_meancov(list(1, 2, 3), list(1, 2, 3), c(1, 1, 1), "frequency")
  expect_equal(wm$cov, 1)
  prob <- SDEProblem(function(u, p, t) u, function(u, p, t) 0.2 * u, c(1, 2), c(0, 1))
  sim <- solve(EnsembleProblem(prob), EM(), trajectories = 10, dt = 0.1, seed = 3)
  expect_equal(timestep_mean(sim, 1), c(1, 2))
  expect_length(get_timestep(sim, 3), 10L)
  expect_length(componentwise_vectors_timepoint(sim, 0.5), 2L)
  expect_equal(timepoint_meanvar(sim, 0.5)$mean, timepoint_mean(sim, 0.5))
  expect_equal(timepoint_median(sim, 0), c(1, 2))
  expect_length(timepoint_quantile(sim, 0.9, 1), 2L)
  ts <- timeseries_steps_mean(sim)
  expect_equal(dim(ts$u), c(11L, 2L))
  expect_length(timeseries_steps_meanvar(sim), 2L)
  expect_equal(dim(timeseries_point_meancov(sim, c(0.5, 1))), c(2L, 2L))
  expect_equal(timeseries_point_mean(sim, c(0, 1))$u[1, ], c(1, 2))
  expect_true(is.list(timestep_meancor(sim, 2, 3)))
  expect_true(is.list(timepoint_weighted_meancov(sim, rep(1, 10), 0.5, 1)))
})

test_that("SciMLBase types and automatic differentiation choices", {
  expect_equal(ReturnCode$Success, "Success")
  expect_true(successful_retcode(ReturnCode$Terminated))
  expect_false(successful_retcode(ReturnCode$MaxIters))
  expect_length(NullParameters(), 0L)
  sol <- ODESolution(c(0, 1), rbind(0, 1), ODEProblem(function(u, p, t) 1, 0, c(0, 1)))
  expect_equal(sol(0.25), 0.25)
  es <- EnsembleSolution(list(1, 2))
  expect_length(es, 2L)
  vdp <- ODEProblem(function(u, p, t) c(u[2], 10 * ((1 - u[1]^2) * u[2]) - u[1]), c(2, 0), c(0, 10))
  ref <- solve(vdp, Rodas5P(), reltol = 1e-8, abstol = 1e-10)
  for (ad in list(AutoFiniteDiff(), AutoFiniteDiff("central"), AutoForwardDiff(), AutoSparse(AutoForwardDiff())))
    expect_equal(tail(solve(vdp, Rodas5P(autodiff = ad), reltol = 1e-8, abstol = 1e-10)$u, 1)[[1]],
                 tail(ref$u, 1)[[1]], tolerance = 1e-5)
  expect_s3_class(FBDF(autodiff = AutoFiniteDiff())$autodiff, "AutoFiniteDiff")
  expect_error(Rodas5P(autodiff = 1), "autodiff")
  expect_s3_class(PolyesterThreads(), "ThreadingOption")
})

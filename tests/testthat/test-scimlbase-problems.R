test_that("structured ODE problems solve as their flat forms", {
  so <- SecondOrderODEProblem(function(du, u, p, t) -u, 0, 1, c(0, pi))
  expect_s3_class(so, "DynamicalODEProblem")
  expect_equal(as.numeric(solve(so, Tsit5(), abstol = 1e-10, reltol = 1e-10)(pi)), c(0, -1), tolerance = 1e-7)
  sp <- SplitODEProblem(function(u, p, t) -2 * u, function(u, p, t) u, 1, c(0, 1))
  expect_s3_class(sp, "SplitODEProblem")
  expect_equal(sp$f$f1(1, NULL, 0), -2)
  expect_equal(solve(sp, Tsit5(), abstol = 1e-10, reltol = 1e-10)(1), exp(-1), tolerance = 1e-8)
  dp <- DynamicalODEProblem(function(v, u, p, t) -u, function(v, u, p, t) v, 1, 0, c(0, pi / 2))
  expect_equal(as.numeric(solve(dp, Tsit5(), abstol = 1e-10, reltol = 1e-10)(pi / 2)), c(0, 1), tolerance = 1e-7)
  ip <- IncrementingODEProblem(function(du, u, p, t, a, b) a * (-u) + b * du, 1, c(0, 1))
  expect_equal(solve(ip, Tsit5(), abstol = 1e-10, reltol = 1e-10)(1), exp(-1), tolerance = 1e-8)
})

test_that("structured SDE, DDE and BVP problems", {
  ss <- SplitSDEProblem(function(u, p, t) -u, function(u, p, t) 0 * u, function(u, p, t) 0.1, 1, c(0, 1))
  expect_s3_class(ss, "SplitSDEProblem")
  expect_equal(solve(ss, EM(), dt = 0.01, seed = 1)$retcode, "Success")
  ds <- DynamicalSDEProblem(function(v, u, p, t) -u, function(v, u, p, t) v, function(v, u, p, t) 0.1, 0, 1, c(0, 1))
  expect_equal(solve(ds, EM(), dt = 0.01, seed = 1)$retcode, "Success")
  h <- function(p, t) c(0, 1)
  dd <- SecondOrderDDEProblem(function(du, u, hist, p, t) -u, 0, 1, h, c(0, 1))
  expect_equal(as.numeric(solve(dd, MethodOfSteps(Tsit5()))(1)), c(-sin(1), cos(1)), tolerance = 1e-4)
  tp <- TwoPointBVProblem(function(u, p, t) c(u[2], -u[1]),
                          list(function(ua, p) ua[1], function(ub, p) ub[1] - 1), c(0, 1), c(0, pi / 2))
  s <- solve(tp, MIRK4(), dt = 0.05)
  expect_equal(s(pi / 4)[1], sin(pi / 4), tolerance = 1e-5)
  so <- SecondOrderBVProblem(function(du, u, p, t) -u, function(du, u, p, t) c(u(t[1]), u(t[2]) - 1), 0, c(0, pi / 2))
  s2 <- solve(so, MIRK4(), dt = 0.05)
  expect_equal(s2(pi / 4)[2], sin(pi / 4), tolerance = 1e-5)
  t2 <- TwoPointSecondOrderBVProblem(function(du, u, p, t) -u,
                                     list(function(dua, ua, p) ua, function(dub, ub, p) ub - 1), 0, c(0, pi / 2))
  s3 <- solve(t2, MIRK4(), dt = 0.05)
  expect_equal(s3(pi / 4)[2], sin(pi / 4), tolerance = 1e-5)
})

test_that("analytical and integral problems", {
  sol <- solve(AnalyticalProblem(function(u0, p, t) u0 * exp(-t), 1, c(0, 1)), dt = 0.5)
  expect_equal(unlist(sol$u), exp(-c(0, 0.5, 1)))
  expect_equal(solve(IntegralProblem(function(x, p) exp(-x^2), c(-Inf, Inf)))$u, sqrt(pi), tolerance = 1e-8)
  expect_equal(solve(IntegralProblem(function(x, p) x[1] * x[2], list(c(0, 0), c(1, 2))))$u, 1, tolerance = 1e-8)
  vec <- solve(IntegralProblem(function(x, p) c(x, x^2), c(0, 1)))
  expect_equal(vec$u, c(1 / 2, 1 / 3), tolerance = 1e-10)
  b <- solve(IntegralProblem(BatchIntegralFunction(function(X, p) colSums(X^2)), c(0, 1)))
  expect_equal(b$u, 1 / 3, tolerance = 1e-10)
  x <- seq(0, pi, length.out = 101)
  expect_equal(solve(SampledIntegralProblem(sin(x), x), SimpsonsRule())$u, 2, tolerance = 1e-7)
  expect_equal(solve(SampledIntegralProblem(sin(x), x))$u, 2, tolerance = 1e-3)
  Y <- rbind(sin(x), cos(x))
  expect_equal(solve(SampledIntegralProblem(Y, x, dim = 2), SimpsonsRule())$u, c(2, 0), tolerance = 1e-6)
})

test_that("SciML operators", {
  L <- MatrixOperator(matrix(c(2, 0, 1, 3), 2))
  expect_equal(op_apply(L, c(1, 1)), c(3, 3))
  D <- DiagonalOperator(c(1, 2))
  expect_equal(as.matrix(L + 2 * D), matrix(c(4, 0, 1, 7), 2))
  expect_equal(solve(L, c(3, 3)), c(1, 1))
  expect_equal(as.matrix(L * D), matrix(c(2, 0, 1, 3), 2) %*% diag(c(1, 2)))
  Tm <- update_coefficients(MatrixOperator(diag(2), function(A, u, p, t) t * diag(2)), NULL, NULL, 3)
  expect_equal(as.matrix(Tm), 3 * diag(2))
  A <- matrix(1:4, 2); B <- matrix(c(1, 0, 2, 1), 2)
  K <- TensorProductOperator(A, B)
  expect_equal(op_apply(K, 1:4), as.numeric(kronecker(A, B) %*% (1:4)))
  expect_equal(solve(K, op_apply(K, 1:4)), 1:4)
  expect_equal(as.matrix(kronsum(A, B)), kronecker(A, diag(2)) + kronecker(diag(2), B))
  expect_equal(exp(MatrixOperator(diag(c(1, 2)))), diag(exp(c(1, 2))))
  R <- matrix(c(0, -1, 1, 0), 2)
  expect_equal(exp(MatrixOperator(R)), matrix(c(cos(1), -sin(1), sin(1), cos(1)), 2), tolerance = 1e-12)
  W <- WOperator(NULL, 0.5, matrix(c(1, 2, 3, 4), 2))
  expect_equal(as.matrix(W), matrix(c(1, 2, 3, 4), 2) - 2 * diag(2))
  expect_true(jacobian_stale(W)); mark_jacobian_current(W); expect_false(jacobian_stale(W))
  fo <- FunctionOperator(function(v, u, p, t) 2 * v, numeric(3), op_inverse = function(v, u, p, t) v / 2)
  expect_equal(as.matrix(fo), 2 * diag(3))
  expect_equal(solve(fo, c(2, 4, 6)), c(1, 2, 3))
  af <- AddVector(c(1, 1))
  expect_equal(op_apply(af, c(1, 2)), c(2, 3))
  expect_false(islinear(af))
  bd <- BlockDiagonalOperator(diag(2), matrix(3))
  expect_equal(dim(bd), c(3L, 3L))
  expect_true(issquare(L) && isconstant(L) && has_ldiv(L) && isconvertible(L))
  expect_true(iscached(cache_operator(L, c(1, 1))))
})

test_that("bracketing algorithms", {
  prob <- IntervalNonlinearProblem(function(u, p) u^3 - 2, c(0, 2))
  for (alg in list(Alefeld(), ModAB(), Ridder(), Muller()))
    expect_equal(solve(prob, alg, abstol = 1e-12)$u, 2^(1 / 3), tolerance = 1e-9, info = alg$name)
  expect_identical(solve(prob, Ridder())$retcode, "Success")
})

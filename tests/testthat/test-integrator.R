test_that("init, step and solve! follow SciMLBase's integrator interface", {
  prob <- ODEProblem(function(u, p, t) -p * u, 1, c(0, 1), 2)
  integ <- init(prob, Tsit5(), reltol = 1e-10, abstol = 1e-12)
  expect_s3_class(integ, "DEIntegrator")
  step_integrator(integ)
  expect_gt(integ$t, 0)
  expect_gt(integ$dt, 0)
  step_integrator(integ, 0.25, stop_at_tdt = TRUE)
  expect_equal(integ$u, exp(-2 * integ$t), tolerance = 1e-9)
  expect_equal(integ$interp(integ$t - 0.01), exp(-2 * (integ$t - 0.01)), tolerance = 1e-8)
  set_u(integ, 2 * integ$u)
  sol <- solve_integrator(integ)
  expect_equal(tail(sol$u, 1)[[1]], 2 * exp(-2), tolerance = 1e-8)
  expect_identical(solve_integrator(integ), sol)
  reinit(integ)
  expect_equal(integ$t, 0)
  expect_equal(tail(solve_integrator(integ)$u, 1)[[1]], exp(-2), tolerance = 1e-8)
  # stepping the integrator gives the solution of solve()
  expect_equal(solve_integrator(init(prob, Tsit5()))$u, solve(prob, Tsit5())$u)
  i2 <- init(prob, Tsit5(), saveat = 0.5)
  add_saveat(i2, 0.25)
  expect_equal(solve_integrator(i2)$t, c(0, 0.25, 0.5, 1))
  i3 <- init(prob, Tsit5())
  set_proposed_dt(i3, 0.01)
  expect_equal(get_proposed_dt(i3), 0.01)
  step_integrator(i3)
  expect_equal(i3$t, 0.01)
  set_abstol(i3, 1e-9)
  set_reltol(i3, 1e-9)
  expect_equal(i3$opts[c("abstol", "reltol")], list(abstol = 1e-9, reltol = 1e-9))
  expect_equal(get_du(i3), -2 * i3$u)
  set_t(i3, 0.5)
  step_integrator(i3)
  expect_gt(i3$t, 0.5)
  savevalues(i3)
  expect_equal(tail(i3$sol$t, 1), i3$t)
  # SDEs
  sp <- SDEProblem(function(u, p, t) -u, function(u, p, t) 0.1 * u, 1, c(0, 1))
  is <- init(sp, SOSRI(), seed = 1)
  step_integrator(is)
  ss <- solve_integrator(is)
  expect_s3_class(ss, "RODESolution")
  expect_true(length(ss$W$t) > 1)
  expect_error(init(DiscreteProblem(1, c(0, 1))), "not for DiscreteProblem")
})

test_that("SDE integrators own their generator and reinit restarts the noise", {
  # reinit_noise!: the second run starts the noise at t0 again
  p <- SDEProblem(function(u, p, t) 0, function(u, p, t) 1, 0, c(0, 1),
                  noise = NoiseFunction(0, function(u, p, t) t))
  i <- init(p, EM(), dt = 0.5)
  expect_equal(tail(solve_integrator(i)$u, 1)[[1]], 1)
  reinit(i)
  expect_equal(tail(solve_integrator(i)$u, 1)[[1]], 1)
  sp <- SDEProblem(function(u, p, t) -u, function(u, p, t) 0.1 * u, 1, c(0, 1))
  i <- init(sp, EM(), dt = 0.1, seed = 3)
  solve_integrator(i)
  reinit(i)
  s <- solve_integrator(i)
  expect_equal(s$W$W[1, ], 0)
  expect_length(s$W$t, 11L)
  # a seeded integrator follows its own stream: other integrators and other
  # draws do not change its path, and the caller's stream is left alone
  ref <- solve(sp, SOSRI(), seed = 1)
  set.seed(99)
  i1 <- init(sp, SOSRI(), seed = 1)
  step_integrator(i1)
  i2 <- init(sp, SOSRI(), seed = 2)
  step_integrator(i2)
  junk <- stats::rnorm(10)
  expect_equal(solve_integrator(i1)$u, ref$u)
  after <- stats::runif(1)
  set.seed(99)
  stats::rnorm(10)
  expect_identical(after, stats::runif(1))
})

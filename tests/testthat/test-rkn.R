rkn_check <- function(r) {
  prob <- rkn_test_probs[[r$case]]()
  alg <- get(r$alg)()
  sol <- if (!is.null(r$dt)) solve(prob, alg, dt = r$dt, adaptive = FALSE)
    else if (!is.null(r$tol)) solve(prob, alg, reltol = r$tol, abstol = r$tol) else solve(prob, alg)
  lab <- paste(r$alg, r$case, if (!is.null(r$dt)) "fixed" else "adaptive", r$tol %||% "")
  st <- sol$stats
  expect_identical(c(st$nf, st$nf2, st$naccept, st$nreject, length(sol$t)),
                   as.integer(c(r$nf, r$nf2, r$naccept, r$nreject, r$nt)), label = lab)
  expect_equal(sol$t[2], r$t2, tolerance = 1e-12, label = lab)
  if (!r$alg %in% c("IRKN3", "IRKN4")) {
    expect_equal(unname(sol$u[[length(sol$t)]]), r$u, tolerance = 1e-12, label = lab)
    # adaptive: rounding in the error estimates moves the step times by up
    # to 1e-7 (same counts), which the cubic Hermite interpolant feels
    if (!is.null(r$tq)) expect_equal(unname(sol(r$tq)), r$uq, tolerance = if (is.null(r$dt)) 1e-10 else 1e-12,
                                     label = lab)
  }
  sol
}

test_that("the RKN methods match OrdinaryDiffEqRKN", {
  for (r in rkn_refs) rkn_check(r)
})

test_that("DPRKN6 interpolates with its sixth order dense output at saveat", {
  # tools/rkn-probe.jl: P2, reltol = abstol = 1e-8, saveat = c(0.5, 1.7, 2.9)
  sol <- solve(rkn_test_probs$P2(), DPRKN6(), reltol = 1e-8, abstol = 1e-8, saveat = c(0.5, 1.7, 2.9))
  expect_equal(sol$t, c(0.5, 1.7, 2.9))
  expect_equal(unname(sol$u[[2]]), rkn_dprkn6_saveat, tolerance = 1e-12)
})

test_that("the velocity independent methods refuse a velocity dependent f1", {
  for (alg in list(DPRKN6(), ERKN4(), Nystrom4VelocityIndependent(), IRKN3())) {
    expect_error(solve(rkn_test_probs$P3(), alg, dt = 0.1), class = "RKNVelocityDependenceError")
  }
  expect_error(solve(rkn_test_probs$P3(), DPRKN8()), "does not depend on the first derivative")
  # the velocity dependent methods accept it, and an f1 that ignores v passes the probe
  expect_identical(solve(rkn_test_probs$P3(), Nystrom4(), dt = 0.1)$retcode, "Success")
  sentinel_f1 <- function(v, u, p, t) -u
  prob <- SecondOrderODEProblem(sentinel_f1, c(0.5, -0.3), c(1, 0.2), c(0, 1))
  expect_identical(solve(prob, DPRKN5())$retcode, "Success")
})

test_that("IRKN3 and IRKN4 keep their order on forced problems", {
  # Upstream evaluates the second stage of IRKN3 from the acceleration of the
  # previous point and builds the first step stages of IRKN4 from the wrong
  # accelerations and node; both then converge at second order on u'' = -u + t.
  # The exact solution is u = t + A cos t + B sin t.
  A <- c(1, 0.2); B <- c(-0.5, -1.3)
  ex <- c(1 - A * sin(1) + B * cos(1), 1 + A * cos(1) + B * sin(1))
  for (case in list(list(IRKN3, 3), list(IRKN4, 4))) {
    err <- vapply(c(0.05, 0.025), function(dt) {
      sol <- solve(rkn_test_probs$P5(), case[[1]](), dt = dt, adaptive = FALSE)
      max(abs(sol$u[[length(sol$t)]] - ex))
    }, 0)
    expect_gt(log2(err[1] / err[2]), case[[2]] - 0.2)
  }
})


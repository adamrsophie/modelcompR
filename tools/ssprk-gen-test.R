# Writes tests/testthat/test-ssprk.R from the runs of tools/ssprk-probe.jl:
#
#   julia --project=tools/julia tools/ssprk-probe.jl > runs.tsv
#   Rscript tools/ssprk-gen-test.R runs.tsv tests/testthat/test-ssprk.R
args <- commandArgs(trailingOnly = TRUE)
runs <- read.delim(args[1], header = FALSE, stringsAsFactors = FALSE, quote = "", colClasses = "character")
names(runs) <- c("alg", "case", "n", "nf", "nacc", "nrej", "u", "t", "dense")
runs$dense[is.na(runs$dense)] <- ""
# SSPRK932 stalls in adaptive mode (its defective tableau, as in Julia) and
# saves up to a million points: those runs keep the first 200 saved points
# (n = 0), compared with a run stopped by maxiters
head_hex <- function(s, k) paste(head(strsplit(s, ",", fixed = TRUE)[[1]], k), collapse = ",")
big <- as.integer(runs$n) > 1000L
runs$u[big] <- vapply(runs$u[big], head_hex, "", k = 400L, USE.NAMES = FALSE)
runs$t[big] <- vapply(runs$t[big], head_hex, "", k = 200L, USE.NAMES = FALSE)
runs$dense[big] <- ""
runs$n[big] <- "0"
# the stalled saveat run takes a million steps: it is left out (Julia saves
# only t0 when maxiters stops it, R also saves the stopping point)
keep <- !(as.numeric(runs$nf) > 1e6 & runs$case == "saveat")
runs <- runs[keep, ]
lines <- sprintf('  "%s", "%s", %s, %s, %s, %s,\n    "%s",\n    "%s",\n    "%s",', runs$alg, runs$case, runs$n,
                 runs$nf, runs$nacc, runs$nrej, runs$u, runs$t, runs$dense)
lines[length(lines)] <- sub(",$", "", lines[length(lines)])
hdr <- c(
  "# The SSP methods (R/solvers-ssprk.R, SSPRKMSVS32 and SSPRKMSVS43 in",
  "# R/solvers-erk-extra.R) against the out of place perform_step! of",
  "# OrdinaryDiffEqSSPRK: tools/ssprk-probe.jl runs every method with a fixed",
  "# step, a fixed step with saveat and, for the adaptive ones, with",
  "# tolerances, with step rejections and with saveat. The saved points,",
  "# function evaluations, accepted and rejected steps, every saved state and",
  "# time and the dense output agree to the bit on the reference platform",
  "# (helper-platform.R; elsewhere the states are compared to a tolerance).",
  "# SSPRK932 stalls in adaptive mode as in Julia (its tableau is defective);",
  "# its adaptive runs compare the first 200 saved points. Generated by",
  "# tools/ssprk-gen-test.R.",
  "",
  "ssprk_lv <- function(u, p, t) c(1.5 * u[1] - u[1] * u[2], -3 * u[2] + u[1] * u[2] + 0.1 * t)",
  "ssprk_g <- function(u, p, t) c(-20 * (u[1] - t * (2 - t)), 0.5 * u[1] * u[2])",
  "ssprk_P1 <- ODEProblem(ssprk_lv, c(1, 1), c(0, 1))",
  "ssprk_P2 <- ODEProblem(ssprk_g, c(0, 1), c(0, 2))",
  "ssprk_hex <- function(s) if (nzchar(s)) as.numeric(strsplit(s, \",\", fixed = TRUE)[[1]]) else numeric()",
  "",
  "ssprk_solve <- function(alg, case, maxiters = 1e6) {",
  "  switch(case,",
  "    fixed = solve(ssprk_P1, alg, dt = 0.1, adaptive = FALSE),",
  "    fixed_saveat = solve(ssprk_P1, alg, dt = 0.1, adaptive = FALSE, saveat = c(0.25, 0.65)),",
  "    adaptive = solve(ssprk_P1, alg, reltol = 1e-6, abstol = 1e-8, maxiters = maxiters),",
  "    reject = solve(ssprk_P2, alg, reltol = 1e-4, abstol = 1e-6, dt = 0.5, maxiters = maxiters),",
  "    saveat = solve(ssprk_P1, alg, reltol = 1e-6, abstol = 1e-8, saveat = 0.37))",
  "}",
  "",
  "ssprk_ref <- matrix(c(")
ftr <- c(
  "), ncol = 9, byrow = TRUE)",
  "",
  "test_that(\"the SSP methods reproduce OrdinaryDiffEqSSPRK\", {",
  "  for (i in seq_len(nrow(ssprk_ref))) {",
  "    r <- ssprk_ref[i, ]",
  "    lab <- paste(r[1], r[2])",
  "    if (r[3] == \"0\") {",
  "      s <- suppressWarnings(ssprk_solve(get(r[1])(), r[2], maxiters = 300))",
  "      u <- head(as.numeric(t(do.call(rbind, s$u))), 400L)",
  "      if (ref_platform()) expect_identical(u, ssprk_hex(r[7]), label = lab)",
  "      else expect_equal(u, ssprk_hex(r[7]), tolerance = 1e-10, label = lab)",
  "      next",
  "    }",
  "    s <- ssprk_solve(get(r[1])(), r[2])",
  "    u <- as.numeric(t(do.call(rbind, s$u)))",
  "    if (!ref_platform()) {",
  "      expect_equal(u, ssprk_hex(r[7]), tolerance = 1e-10, label = lab)",
  "      next",
  "    }",
  "    expect_identical(c(length(s$t), s$stats$nf, s$stats$naccept, s$stats$nreject), as.integer(r[3:6]), label = lab)",
  "    expect_identical(u, ssprk_hex(r[7]), label = lab)",
  "    expect_identical(as.numeric(s$t), ssprk_hex(r[8]), label = lab)",
  "    if (nzchar(r[9]))",
  "      expect_identical(unlist(lapply(c(0.03, 0.47, 0.71), s)), ssprk_hex(r[9]), label = lab)",
  "  }",
  "})")
writeLines(c(hdr, lines, ftr), args[2])

# Regenerate R/math-heads.R: the function heads that symcompR evaluates as
# mathematical functions (sin, erf, besselj, ...). Applications of any other
# undeclared function are unknowns of a model, as undefined functions are in
# ModelingToolkit.
#
# Run from the repository root after updating symcompR:
#   Rscript tools/gen_math_heads.R
# This development script reads symcompR's internal registry; the package
# itself only reads the generated vector.

heads <- sort(unique(c(names(symcompR:::.FUNS), "sqrt")))
heads <- heads[grepl("^[A-Za-z][A-Za-z0-9_]*$", heads)]
`%s%` <- function(a, b) paste0(a, b)
ver <- as.character(utils::packageVersion("symcompR"))
lines <- c(
  "# Generated by tools/gen_math_heads.R from symcompR " %s% ver %s% "; do not edit.",
  "# Function heads symcompR evaluates as mathematical functions. Undeclared",
  "# applications of any other function are unknowns (see .undeclared_kind).",
  ".MATH_HEADS <- c(",
  paste0("  ", strwrap(paste0('"', heads, '"', collapse = ", "), width = 76), collapse = "\n"),
  ")")
`%s%` <- function(a, b) paste0(a, b)
writeLines(lines, "R/math-heads.R")
cat(length(heads), "heads written to R/math-heads.R\n")

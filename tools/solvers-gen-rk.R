# Writes R/solvers-erk-methods.R: the explicit Runge-Kutta methods of the
# OrdinaryDiffEq sublibraries as tableaus for the generic stepper of
# R/solvers-erk.R, from the output of tools/solvers-probe-rk.jl.
#
# Run from the repository root:
#   julia --project=tools/julia tools/solvers-probe-rk.jl tools/rk_probe.tsv NAMES.txt
#   Rscript tools/solvers-gen-rk.R tools/rk_probe.tsv
# Methods the package implements by hand (their own dense output) are left
# out; so are the methods listed in `skip` below, which are not one step
# Runge-Kutta methods and are implemented separately.
args <- commandArgs(TRUE)
infile <- if (length(args)) args[1L] else "tools/rk_probe.tsv"
ns <- readLines("NAMESPACE")
exported <- gsub("[`\"]", "", sub("^export[(](.*)[)]$", "\\1", grep("^export[(]", ns, value = TRUE)))
hand <- c("Euler", "Midpoint", "RK4", "BS3", "DP5", "Tsit5", "AutoTsit5", "Vern6", "Vern7", "Vern8", "Vern9",
          "AutoVern6", "AutoVern7", "AutoVern8", "AutoVern9", "AutoDP5")
skip <- c("SSPRKMSVS32", "SSPRKMSVS43", "pRRK22", "pRRK33", "pRRK54", "SplitEuler", "ExplicitRK", "RKO65",
          "FRK65", "Anas5", "KYK2014DGSSPRK_3S2")
lines <- readLines(infile)
tabs <- list()
for (ln in lines) {
  parts <- strsplit(ln, "\t", fixed = TRUE)[[1L]]
  nm <- parts[1L]
  if (nm %in% c(hand, skip) || nm %in% setdiff(exported, character())) next
  kv <- strsplit(parts[-1L], "=", fixed = TRUE)
  fl <- stats::setNames(lapply(kv, `[`, 2L), vapply(kv, `[`, "", 1L))
  num <- function(x) as.numeric(strsplit(x, ",", fixed = TRUE)[[1L]])
  tabs[[nm]] <- list(
    s = as.integer(fl$s), A = num(fl$A), b = num(fl$b), c = num(fl$c),
    btilde = if (!is.null(fl$btilde)) num(fl$btilde),
    order = as.numeric(fl$order), adaptive_order = if (!is.null(fl$adaptive_order)) as.numeric(fl$adaptive_order),
    adaptive = identical(fl$adaptive, "true"), nonlinear_est = identical(fl$nonlinear_est, "true"),
    qmax = if (!is.null(fl$qmax)) as.numeric(fl$qmax), qmin = if (!is.null(fl$qmin)) as.numeric(fl$qmin),
    gamma = if (!is.null(fl$gamma)) as.numeric(fl$gamma), beta1 = if (!is.null(fl$beta1)) as.numeric(fl$beta1),
    beta2 = if (!is.null(fl$beta2)) as.numeric(fl$beta2), controller = fl$controller,
    pid_beta = if (!is.null(fl$pid_beta)) num(fl$pid_beta),
    pid_accept_safety = if (!is.null(fl$pid_accept_safety)) as.numeric(fl$pid_accept_safety),
    ssp = if (!is.null(fl$ssp)) as.numeric(fl$ssp))
}
fmt <- function(x) {
  if (is.null(x)) return("NULL")
  if (is.character(x)) return(deparse(x))
  if (is.logical(x)) return(if (x) "TRUE" else "FALSE")
  v <- vapply(x, function(y) if (y == 0) "0" else format(y, digits = 17), "")
  if (length(v) == 1L) v else paste0("c(", paste(v, collapse = ", "), ")")
}
out <- c(
  "# Generated by tools/solvers-gen-rk.R from tools/solvers-probe-rk.jl; do not edit.",
  "# The explicit Runge-Kutta methods of the OrdinaryDiffEq sublibraries",
  "# (OrdinaryDiffEqLowOrderRK, OrdinaryDiffEqHighOrderRK, OrdinaryDiffEqSSPRK,",
  "# OrdinaryDiffEqLowStorageRK, OrdinaryDiffEqFeagin, OrdinaryDiffEqVerner,",
  "# OrdinaryDiffEqSIMDRK): Butcher tableaus (A row major), embedded error",
  "# weights and step size controller settings, recovered from one step of",
  "# each Julia method. The stepper is .erk_step in R/solvers-erk.R.",
  "",
  ".ERK_TABLEAUS <- list(")
nms <- sort(names(tabs))
for (i in seq_along(nms)) {
  tb <- tabs[[nms[i]]]
  fields <- vapply(names(tb), function(k) paste0("    ", k, " = ", fmt(tb[[k]])), "")
  out <- c(out, paste0("  ", nms[i], " = list("), paste0(fields, c(rep(",", length(fields) - 1L), "")),
           paste0("  )", if (i < length(nms)) "," else ""))
}
out <- c(out, ")", "")
for (nm in nms) {
  out <- c(out, "#' @rdname explicit_rk_methods", "#' @export",
           paste0(nm, " <- function(stage_limiter = NULL, step_limiter = NULL, thread = NULL, ...)"),
           paste0("  .erk_alg(\"", nm, "\", stage_limiter = stage_limiter, step_limiter = step_limiter, ...)"), "")
}
writeLines(out, "R/solvers-erk-methods.R")
cat(length(nms), "methods written\n")

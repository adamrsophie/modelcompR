show_alg(a) = join([string(getfield(a, k)) for k in (:min_order, :init_order, :max_order, :sequence)], ",")
println("ctor\tDeuflhard\t", show_alg(ExtrapolationMidpointDeuflhard(min_order = 0, init_order = -1, max_order = -2)))
println("ctor\tHairerWanner\t", show_alg(ExtrapolationMidpointHairerWanner(min_order = 4, init_order = 2, max_order = 3)))
println("ctor\tImplicitEuler\t", show_alg(ImplicitEulerExtrapolation(min_order = 1, init_order = 1, max_order = 1)))
println("ctor\tBarycentric\t", show_alg(ImplicitEulerBarycentricExtrapolation(min_order = 6, init_order = 2, max_order = 2, sequence = :foo)))
println("ctor\tsf\t", ExtrapolationMidpointHairerWanner(sequence_factor = 3).sequence_factor)
for (lab, f) in [("max_order16", () -> solve(PROBS["lv"], ExtrapolationMidpointDeuflhard(max_order = 16))),
                 ("max_order16bary", () -> solve(PROBS["vdp"], ImplicitEulerBarycentricExtrapolation(max_order = 16))),
                 ("iee16", () -> solve(PROBS["vdp"], ImplicitEulerExtrapolation(max_order = 16), abstol = 1e-6, reltol = 1e-6).retcode),
                 ("mass", () -> solve(ODEProblem(ODEFunction(vdp; jac = vdpj, mass_matrix = [1.0 0.0; 0.0 0.0]), [2.0, 0.0], (0.0, 1.0), [10.0]),
                                       ImplicitEulerExtrapolation()))]
    msg = try
        string(f())
    catch e
        "ERROR " * first(split(sprint(showerror, e), "\n"))
    end
    println("check\t", lab, "\t", msg)
end

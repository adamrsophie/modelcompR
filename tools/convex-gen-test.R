  cone <- function(cn) switch(cn$type, ZeroConeT = paste0("Zero:", cn$dim), NonnegativeConeT = paste0("Nonnegative:", cn$dim),
    SecondOrderConeT = paste0("SecondOrder:", cn$dim), ExponentialConeT = "Exponential", PowerConeT = "Power",
    GenPowerConeT = paste0("GenPower:", length(cn$alpha), ":", cn$dim2), PSDTriangleConeT = paste0("PSDTriangle:", cn$dim))
  list(retcode = sol$retcode, iters = sol$original$iterations, objective = sol$objective, u = sol$u, dual = sol$dual,
       cones = paste(vapply(S$data$cones, cone, ""), collapse = ","), n = S$data$n, m = S$data$m,
       atoms = paste(vapply(cache$dpp$atomsets, function(s) paste0(s$name, ":", s$dimension), ""), collapse = ","),
       perm = S$kkt$solver$ldl$perm, chordal = !is.null(S$data$chordal_info), active = cache$model$active)
}

# Clarabel.jl's dual completion indexes an OrderedSet and throws whenever a
# PSD cone is decomposed (an upstream bug); the port completes the dual, so
# such a case is compared with the probe run without the completion
cvx_upstream_bug <- function(want) identical(want$retcode, "ERROR") &&
  startsWith(want$error, "MethodError: no method matching getindex(::OrderedCollections.OrderedSet")

# the R message of a Julia error: the ConvexOptimization messages verbatim,
# the MOI ones by their cause
cvx_error_key <- function(msg) {
  if (startsWith(msg, "UnsupportedConstraint")) return(sub("^.*MathOptInterface\\.([A-Za-z]+)[{,].*$", "\\1", msg))
  if (startsWith(msg, "MathOptInterface.GetAttributeNotAllowed"))
    return(sub("^.*(Bridge of type `[A-Za-z]+` does not support accessing the attribute).*$", "\\1", msg))
  msg
}

cvx_run <- function(prob, alg, sweep = NULL) {
  tryCatch(suppressWarnings({
    cache <- init(prob, alg)
    cvx_record(cache, solve_integrator(cache))
  }), error = function(e) list(retcode = "ERROR", error = conditionMessage(e)))
}

# the distinct bridges print_active_bridges lists, as Constraint.X or
# Variable.X
cvx_bridge_names <- function(s) {
  m <- regmatches(s, gregexpr("MOIB\\.(Constraint|Variable)\\.[A-Za-z]+", s))[[1]]
  sort(unique(sub("^MOIB\\.", "", m)))
}

cvx_check <- function(name, got, want, ref) {
  if (identical(want$retcode, "ERROR")) {
    if (cvx_upstream_bug(want)) {
      # the solve itself, up to the completion that throws upstream
      sv <- ref[[paste0(name, "_solver")]]
      if (!is.null(sv) && identical(got$retcode, "Success")) {
        expect_identical(sv$status, "SOLVED", label = paste(name, "Julia status"))
        expect_identical(got$iters, sv$iters, label = paste(name, "iterations"))
        expect_identical(got$cones, sv$cones, label = paste(name, "cones"))
        expect_identical(c(got$n, got$m), c(sv$n, sv$m), label = paste(name, "size"))
      }
      alt <- ref[[paste0(name, "_nocd")]]
      if (is.null(alt)) return(expect_identical(got$retcode, "Success", label = paste(name, "retcode")))
      expect_identical(got$retcode, alt$retcode, label = paste(name, "retcode"))
      if (identical(got$retcode, "ERROR")) return(invisible())
      # the completion only fills the entries the cliques leave out
      gd <- unlist(got$dual); ad <- unlist(alt$dual)
      expect_identical(length(gd), length(ad), label = paste(name, "dual length"))
      expect_equal(gd[ad != 0], ad[ad != 0], tolerance = if (grepl("Exponential|Power", alt$cones)) 1e-4 else 1e-7,
                   label = paste(name, "completed dual"))
      alt$dual <- got$dual
      return(cvx_compare(name, got, alt))
    }
    expect_identical(got$retcode, "ERROR", label = paste(name, "rejected"))
    key <- cvx_error_key(want$error)
    if (key == want$error) expect_identical(got$error, want$error, label = paste(name, "error message"))
    else expect_true(grepl(key, got$error, fixed = TRUE), label = paste(name, "error message:", got$error))
    return(invisible())
  }
  expect_identical(got$retcode, want$retcode, label = paste(name, "retcode", got$error))
  if (identical(got$retcode, "ERROR")) return(invisible())
  cvx_compare(name, got, want)
}

# Julia orders the atoms of a sum by the hash order of its Dict of terms,
# which R cannot reproduce; these cases lower the same atoms in another
# order, so their variables and the AMD permutation are permuted
cvx_hash_order <- c("abs", "square", "con_two")

cvx_compare <- function(name, got, want) {
  # the exponential and power cones solve their barrier systems with FMA and
  # BLAS sums that drift by rounding, so their final iterates agree to 1e-4
  # and the iteration count may differ near the tolerances
  nonsym <- grepl("Exponential|Power", want$cones)
  tol <- if (nonsym) 1e-4 else 1e-7
  expect_identical(got$retcode, want$retcode, label = paste(name, "retcode"))
  if (!nonsym) expect_identical(got$iters, want$iters, label = paste(name, "iterations"))
  expect_identical(got$cones, want$cones, label = paste(name, "cones"))
  expect_identical(c(got$n, got$m), c(want$n, want$m), label = paste(name, "size"))
  if (name %in% cvx_hash_order) {
    expect_identical(sort(strsplit(got$atoms, ",")[[1]]), sort(strsplit(want$atoms, ",")[[1]]),
                     label = paste(name, "atoms"))
  } else {
    expect_identical(got$atoms, want$atoms, label = paste(name, "atoms"))
    expect_identical(as.integer(got$perm), as.integer(want$perm), label = paste(name, "AMD permutation"))
  }
  expect_identical(got$chordal, want$chordal, label = paste(name, "chordal decomposition"))
  expect_identical(sort(got$active), cvx_bridge_names(want$bridges), label = paste(name, "active bridges"))
  # an infeasible or unbounded exit divides by a vanishing tau, so its u and
  # objective are certificates whose size is not reproducible to 1e-7
  if (want$retcode != "Success") return(invisible())
  expect_equal(got$objective, want$objective, tolerance = tol, label = paste(name, "objective"))
  expect_equal(got$u, want$u, tolerance = tol, label = paste(name, "u"))
  expect_equal(got$dual, want$dual, tolerance = tol, label = paste(name, "dual"))
}
)---"


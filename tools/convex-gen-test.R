# Writes tests/testthat/test-convex.R from the output of tools/convex-probe.jl:
#   REF=convex.tsv OUT=tests/testthat/test-convex.R Rscript tools/convex-gen-test.R
# Without REF only the behavior tests (the ported ConvexOptimization.jl test
# set, checked against analytic optima) are written. With REF every probe
# case is also compared with ConvexOptimization.jl and Clarabel.jl: the same
# return code, Clarabel iteration count, cones, problem size, lowered atoms
# and AMD permutation, whether a chordal decomposition ran, the active
# bridges, and u, objective and duals to a relative 1e-7 (the floating point
# sums of BLAS are not reproduced bit for bit). A case Julia rejects must be
# rejected with the same message.
out <- Sys.getenv("OUT", "tests/testthat/test-convex.R")
refpath <- Sys.getenv("REF")
hexvec <- function(s) if (is.na(s) || !nzchar(s)) "numeric()" else paste0("c(", gsub(",", ", ", s), ")")
refs <- character()
if (nzchar(refpath)) {
  ref <- read.delim(refpath, header = FALSE, stringsAsFactors = FALSE, colClasses = "character", na.strings = NULL)
  for (k in seq_len(nrow(ref))) {
    r <- ref[k, ]
    if (r[[2]] == "SOLVER") {
      # the solver state of a Julia solve that threw in the dual completion
      refs[k] <- sprintf("  %s_solver = list(status = \"%s\", iters = %sL, cones = \"%s\", n = %sL, m = %sL)",
                         r[[1]], r[[3]], r[[4]], r[[5]], r[[6]], r[[7]])
      next
    }
    if (r[[2]] == "ERROR") {
      # the MOI messages go on to print the model tree, which is not ASCII
      msg <- sub("  (## More information|To fix this error|If you encountered).*$", "", r[[3]])
      refs[k] <- sprintf("  %s = list(retcode = \"ERROR\", error = %s)", r[[1]], deparse(msg, width.cutoff = 500L))
      next
    }
    duals <- if (nzchar(r[[6]])) paste0("list(", paste(vapply(strsplit(r[[6]], ";", fixed = TRUE)[[1]], hexvec, ""),
                                                 collapse = ", "), ")") else "list()"
    refs[k] <- sprintf(paste0("  %s = list(retcode = \"%s\", iters = %sL, objective = %s, u = %s,\n",
                              "    dual = %s,\n    cones = \"%s\", n = %sL, m = %sL, atoms = \"%s\",\n",
                              "    perm = c(%s), chordal = %s,\n    bridges = %s)"),
                       r[[1]], r[[2]], r[[3]], r[[4]], hexvec(r[[5]]), duals, r[[7]], r[[8]], r[[9]], r[[10]],
                       gsub(",", ", ", r[[11]]), if (r[[12]] == "chordal") "TRUE" else "FALSE",
                       deparse(r[[13]], width.cutoff = 500L))
  }
}


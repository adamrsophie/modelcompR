    constraints = list(ConeConstraint(function(u, p) u[n + seq_len(nv)] - 1, MOI$Zeros(nv)),
                       ConeConstraint(function(u, p) do.call(c, f(u, n)), MOI$PositiveSemidefiniteConeSquare(n))))
}

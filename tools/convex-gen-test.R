test_that("problem data that is not disciplined-parametrized is rejected", {
  Z1 <- MOI$Zeros(1)
  pprob <- function(f, p, ...) ConvexOptimizationProblem(f, c(0.5, 0.5), p, lb = c(-10, -10), ub = c(10, 10), ...)
  lin <- function(u, p) u[1] + u[2]
  con <- function(g) list(ConeConstraint(g, Z1))
  # u[1]^2 is a lowerable quadratic atom; u[1]^3 is not
  expect_error(solve(pprob(function(u, p) p[1] * u[1]^3, 1), cvx_alg), "affine in the optimization variables")
  expect_error(solve(pprob(lin, 1, constraints = con(function(u, p) u[1]^2 + p[1] * u[2] - 1)), cvx_alg),
               "not affine in the variables")
  expect_error(solve(pprob(function(u, p) norm(u^2 - p[1], "2"), 1), cvx_alg), "not certified convex")
  expect_error(solve(pprob(function(u, p) u[1] * u[2] + p[1] * u[1], 1), cvx_alg),
               "still contains the optimization variable")
  expect_error(solve(pprob(lin, 1, constraints = con(function(u, p) u[1] * u[2] + p[1] - 1)), cvx_alg),
               "still contains the optimization variable")
  expect_error(solve(pprob(lin, 1, constraints = con(function(u, p) p[1] * u[1] + u[2] - 1)), cvx_alg),
               "parameter-dependent coefficient")
  expect_error(solve(pprob(function(u, p) norm(p[1] * u - 1, "2"), 1), cvx_alg), "parameter-dependent coefficient")
  expect_error(solve(pprob(function(u, p) p[1] * p[2] * u[1] + u[2], c(1, 2)), cvx_alg),
               "not affine in the parameters")
  expect_error(solve(pprob(function(u, p) u[1] + p[1]^3, 2), cvx_alg), "not affine in the parameters")
  expect_error(solve(pprob(lin, 2, constraints = con(function(u, p) u[1] + u[2] - 1 / p[1])), cvx_alg),
               "not affine in the parameters")
  # a parameter-only atom is exact parameter data, evaluated at every p
  cache <- init(pprob(function(u, p) exp(p[1]) * u[1] + u[2], 1), cvx_alg)
  for (th in c(1, -1)) {
    cache <- reinit(cache, p = th)
    sol <- solve_integrator(cache)
    expect_equal(sol$u, c(-10, -10), tolerance = 1e-5)
    expect_equal(sol$objective, -10 * (exp(th) + 1), tolerance = 1e-5)
  }
  expect_error(solve(pprob(function(u, p) u[1] + p[1] * norm(u - 1, "2"), -2), cvx_alg),
               "Lowering an atom through its epigraph")
  expect_true(successful_retcode(solve(pprob(function(u, p) u[1] + p[1] * norm(u - 1, "2"), 2), cvx_alg)$retcode))
  expect_error(solve(pprob(lin, matrix(c(1, 3, 2, 4), 2)), cvx_alg), "must be an `AbstractVector`")
  expect_error(solve(pprob(lin, list(1)), cvx_alg), "must be an `AbstractVector`")
})

test_that("reinit validates p without doing symbolic work", {
  prob <- ConvexOptimizationProblem(function(u, p) p[1] * u[1] + u[2], c(0.5, 0.5), c(0.5, 0),
                                    constraints = cvx_lp_cons())
  cache <- init(prob, cvx_alg)
  expect_error(reinit(cache, p = list(a = 1)), "symbolic maps")
  expect_error(reinit(cache, p = c(1, 2, 3)), "canonicalized for 2 parameters")
  expect_error(reinit(cache, p = c(NaN, 0)), "non-finite")
  expect_error(reinit(cache, p = c(Inf, 0)), "non-finite")
  expect_error(reinit(cache, p = "a"), "AbstractVector")
  expect_error(reinit(cache, u0 = c(1, 2, 3)), "canonicalized for 2 optimization variables")
  expect_identical(cache$p, c(0.5, 0))
  expect_equal(solve_integrator(cache)$objective, 0.5, tolerance = 1e-6)
  cache <- reinit(cache, u0 = c(0.1, 0.9))
  expect_identical(cache$u0, c(0.1, 0.9))
  expect_equal(solve_integrator(cache)$objective, 0.5, tolerance = 1e-6)
  nprob <- ConvexOptimizationProblem(function(u, p) u[1] + 2 * u[2], c(0.5, 0.5), constraints = cvx_cons())
  ncache <- init(nprob, cvx_alg)
  expect_s3_class(ncache$p, "NullParameters")
  expect_identical(ncache$dpp$m, 0L)
  expect_named(ncache$analysis, c("objective", "constraints"))
  expect_error(reinit(ncache, p = 1), "NullParameters")
  expect_identical(reinit(ncache), ncache)
  expect_equal(solve_integrator(ncache)$objective, 1, tolerance = 1e-6)
})


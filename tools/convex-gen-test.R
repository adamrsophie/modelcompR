cvx_lp_analytic <- function(th) {
  s <- 1 + th[2]
  if (th[1] < 1) list(u = c(s, 0), obj = th[1] * s, d1 = th[1], d2 = c(0, 1 - th[1]))
  else list(u = c(0, s), obj = s, d1 = 1, d2 = c(th[1] - 1, 0))
}
cvx_lp_sweep <- list(c(0.5, 0), c(2, 1), c(-1, 0.5), c(0, 3), c(0.5, 0))

test_that("parametric LP: reinit matches the analytic optimum and a cold solve", {
  prob <- ConvexOptimizationProblem(function(u, p) p[1] * u[1] + u[2], c(0.5, 0.5), c(0.5, 0),
                                    constraints = cvx_lp_cons())
  cache <- init(prob, cvx_alg)
  for (th in cvx_lp_sweep) {
    cache <- reinit(cache, p = th)
    sol <- solve_integrator(cache)
    an <- cvx_lp_analytic(th)
    expect_true(successful_retcode(sol$retcode))
    expect_equal(sol$u, an$u, tolerance = 1e-6)
    expect_equal(sol$objective, an$obj, tolerance = 1e-6)
    expect_equal(sol$dual[[1]], an$d1, tolerance = 1e-6)
    expect_equal(sol$dual[[2]], an$d2, tolerance = 1e-6)
    expect_identical(cache$p, th)
    cold <- solve(remake(prob, p = th), cvx_alg)
    expect_equal(sol$u, cold$u, tolerance = 1e-8)
    expect_equal(sol$objective, cold$objective, tolerance = 1e-8)
    expect_equal(sol$dual, cold$dual, tolerance = 1e-8)
    expect_identical(lengths(sol$dual), vapply(prob$constraints, function(con) MOI$dimension(con$set), 0L))
  }
})

test_that("re-solving at a new p does no symbolic work", {
  ntrace <- 0L
  prob <- ConvexOptimizationProblem(function(u, p) {
    ntrace <<- ntrace + 1L
    p[1] * u[1] + u[2]
  }, c(0.5, 0.5), c(0.5, 0), constraints = cvx_lp_cons())
  cache <- init(prob, cvx_alg)
  expect_identical(ntrace, 1L)
  dpp <- cache$dpp
  for (th in cvx_lp_sweep) {
    cache <- reinit(cache, p = th)
    solve_integrator(cache)
  }
  expect_identical(ntrace, 1L)
  expect_identical(cache$dpp, dpp)
  expect_null(cache$analysis)
})


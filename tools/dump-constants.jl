# Dumps the numeric fields of Julia tableau and constant cache constructors
# as an R list, for the generated R/*-constants.R files.
#
# Run from the repository root:
#   julia --project=tools/julia tools/dump-constants.jl OUT.R LISTNAME Package:Constructor ...
# Each constructor is called with (Float64, Float64), else (Float64), else
# no arguments; real fields and real vectors and matrices are written.
const OUT, LIST = ARGS[1], ARGS[2]
specs = ARGS[3:end]
pkgs = unique(first.(split.(specs, ":")))
for p in pkgs
    @eval using $(Symbol(p))
end
num(x) = x == 0 ? "0" : repr(Float64(x))
function rval(x)
    x isa Bool && return nothing
    x isa Real && return num(x)
    x isa AbstractMatrix{<:Real} && return "matrix(c(" * join(num.(vec(x)), ", ") * "), $(size(x, 1)), $(size(x, 2)))"
    x isa AbstractVector{<:Real} && return "c(" * join(num.(x), ", ") * ")"
    x isa Tuple && all(y -> y isa Real, x) && return "c(" * join(num.(collect(x)), ", ") * ")"
    return nothing
end
clean(s) = replace(s, "α" => "alpha", "β" => "beta", "γ" => "gamma", "δ" => "delta", "θ" => "theta",
                   "μ" => "mu", "κ" => "kappa", "ω" => "omega", "ν" => "nu", "₀" => "0", "₁" => "1", "₂" => "2",
                   "₃" => "3", "₄" => "4", "̃" => "tilde", "ˢ" => "s", "ᵢ" => "i")
open(OUT, "w") do io
    println(io, "# Generated by tools/dump-constants.jl; do not edit.")
    println(io, "# Constants of: ", join(specs, " "))
    println(io)
    println(io, LIST, " <- list(")
    out = String[]
    for s in specs
        p, c = split(s, ":")
        m = getfield(Main, Symbol(p))
        # Package:Constructor/1 calls the one argument (Float64) form
        f = getfield(m, Symbol(replace(c, "/1" => "")))
        v = if endswith(c, "/1")
            f(Float64)
        else
            try f(Float64, Float64) catch
                try f(Float64) catch; f() end
            end
        end
        fields = String[]
        for fn in fieldnames(typeof(v))
            r = rval(getfield(v, fn))
            r === nothing && continue
            push!(fields, "    $(clean(string(fn))) = $(r)")
        end
        nm = replace(c, "ConstantCache" => "", "Tableau" => "", "construct" => "", "/1" => "")
        push!(out, "  `$(nm)` = list(\n" * join(fields, ",\n") * "\n  )")
        println(stderr, "OK ", s)
        flush(stderr)
    end
    println(io, join(out, ",\n"))
    println(io, ")")
end

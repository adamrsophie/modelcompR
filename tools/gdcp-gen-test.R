# Writes tests/testthat/test-gdcp.R from the output of tools/gdcp-probe.jl:
#   REF=gdcp.tsv OUT=tests/testthat/test-gdcp.R Rscript tools/gdcp-gen-test.R
# Without REF only the behavior tests (the assertions of SymbolicAnalysis.jl's
# test/dgp.jl and test/lorentz.jl, and the numeric atoms) are written. With
# REF every probe case is also compared with SymbolicAnalysis.jl: the same
# curvature, sign, geodesic curvature and warnings, or the same error.
out <- Sys.getenv("OUT", "tests/testthat/test-gdcp.R")
refpath <- Sys.getenv("REF")
refs <- character()
if (nzchar(refpath)) {
  for (ln in readLines(refpath, encoding = "UTF-8")) {
    r <- strsplit(ln, "\t", fixed = TRUE)[[1L]]
    if (length(r) < 3L) next
    refs <- c(refs, if (r[[2L]] == "ERROR")
      sprintf("  %s = list(error = %s)", r[[1L]], deparse(r[[3L]], width.cutoff = 500L))
    else sprintf("  %s = list(curvature = \"%s\", sign = \"%s\", gcurvature = %s, warnings = %s)", r[[1L]], r[[2L]],
                 r[[3L]], if (r[[4L]] == "nothing") "NULL" else paste0("\"", r[[4L]], "\""),
                 deparse(if (length(r) >= 5L && nzchar(r[[5L]])) strsplit(r[[5L]], " | ", fixed = TRUE)[[1L]]
                         else character(), width.cutoff = 500L)))
  }
}

header <- c(
  "# Generated by tools/gdcp-gen-test.R", if (length(refs))
  "# with reference values from tools/gdcp-probe.jl (SymbolicAnalysis.jl 0.5.8);" else
  "# without reference values; run tools/gdcp-probe.jl and pass REF to compare with Julia.",
  "# Edit the generator, not this file.")

static <- r"---(
gd_X <- MatrixSymbol("X", 3, 3); gd_Y <- MatrixSymbol("Y", 3, 3)
gd_p <- MatrixSymbol("p", 3, 1); gd_x <- MatrixSymbol("x", 3, 1)
gd_S <- SymmetricPositiveDefinite(3); gd_L <- Lorentz(3)
gd_A <- matrix(c(2, 0.5, 0, 0.5, 3, 0.25, 0, 0.25, 1.5), 3)
gd_B <- matrix(c(1, 0.2, 0.1, 0.2, 2, 0.3, 0.1, 0.3, 1), 3)
gd_C <- matrix(c(1.5, 0, 0.3, 0, 1, 0, 0.3, 0, 2.5), 3)
gd_ys <- list(c(1, 0.5, 0.25), c(0, 1, 2))

# the cases of tools/gdcp-probe.jl: the expression and the manifold
gd_cases <- function() {
  X <- gd_X; Y <- gd_Y; p <- gd_p; x <- gd_x; S <- gd_S; L <- gd_L; A <- gd_A; B <- gd_B; C <- gd_C; ys <- gd_ys
  list(
    logdet_conj_inv = list(function() logdet(conjugation(Inverse(X), A)), S),
    logdet_tr_inv = list(function() logdet(tr(Inverse(X))), S),
    lqf_sum = list(function() log_quad_form(ys[[1]], Inverse(X)) + log_quad_form(ys[[2]], Inverse(X)) + 1 / 5 * logdet(X), S),
    brascamp = list(function() logdet(conjugation(X, A)) - logdet(X), S),
    tr_conj = list(function() tr(conjugation(X, A)), S),
    sdiv = list(function() sdivergence(X, A), S),
    sdiv_sum = list(function() sdivergence(X, A) + sdivergence(X, B) + sdivergence(X, C), S),
    dist_sq = list(function() distance(S, A, X)^2, S),
    dist_sq_sum = list(function() distance(S, A, X)^2 + distance(S, B, X)^2, S),
    sqrt_XY = list(function() sqrt(X * Y), S),
    matsqrt = list(function() sdivergence(X, A) + sdivergence(X, diag(3)), S),
    tr_inv_logdet = list(function() tr(Inverse(X)) + logdet(X), S),
    tr_shift_sq = list(function() tr(X + 0.5 * Identity(3))^2, S),
    lqf_inv = list(function() log_quad_form(x, Inverse(X)), S),
    lqf_ys = list(function() log_quad_form(ys, X), S),
    lqf_ys_inv = list(function() log_quad_form(ys, Inverse(X)), S),
    eigsummax_log = list(function() eigsummax(log(X), 2), S),
    schatten_log = list(function() schatten_norm(log(X), 3), S),
    exp_eigsummax_log = list(function() exp(eigsummax(log(X), 2)), S),
    sle = list(function() sum_log_eigmax(X, 2), S),
    sle_exp = list(function() sum_log_eigmax("exp", X, 2), S),
    tr_affine_conj = list(function() tr(affine_map("conjugation", X, B, C)), S),
    hadamard = list(function() hadamard_product(X, B), S),
    logdet_affine_hadamard = list(function() logdet(affine_map("hadamard_product", X, A, B)), S),
    tr_sign = list(function() tr(X), S),
    eigmax_sign = list(function() eigmax(X), S),
    tr_sign_euclid = list(function() tr(X), NULL),
    eigmin = list(function() eigmin(X), S),
    sqrt = list(function() sqrt(X), S),
    norm = list(function() Function("norm")(X), S),
    tr = list(function() tr(X), S),
    eigmax = list(function() eigmax(X), S),
    logdet = list(function() logdet(X), S),
    log_tr = list(function() log(tr(X)), S),
    abs_logdet_tr = list(function() abs(logdet(X) + tr(X)), S),
    lqf_sign = list(function() log_quad_form(c(1, 0, 0), X), S),
    sle_sign = list(function() sum_log_eigmax(X, 2), S),
    lor_dist = list(function() distance(L, c(0, 0, 1), p), L),
    lor_barrier = list(function() lorentz_log_barrier(p), L),
    lor_homq = list(function() lorentz_homogeneous_quadratic(diag(c(2, 2, 1)), p), L),
    lor_homd = list(function() lorentz_homogeneous_diagonal(c(2, 2, 1), p), L),
    lor_ls = list(function() lorentz_least_squares(diag(3), c(0, 0, -1), p), L),
    lor_nhq = list(function() lorentz_nonhomogeneous_quadratic(A, c(0, 0, 2), 1, p), L),
    lor_comp = list(function() 2 * distance(L, c(0, 0, 1), p) + lorentz_log_barrier(p), L),
    lor_homq_neg = list(function() lorentz_homogeneous_quadratic(diag(c(1, 1, -0.5)), p), L),
    lor_homd_neg = list(function() lorentz_homogeneous_diagonal(c(1, 1, -0.5), p), L),
    # symcompR orders the arguments of Min canonically (tr first in older
    # releases, logdet first in newer ones) and upstream reads them in the
    # order written, so of these two only the case symcompR keeps as written
    # is compared
    min_logdet_tr = list(function() Min(logdet(X), tr(X)), S, written = function() list(logdet(X), tr(X))),
    min_tr_logdet = list(function() Min(tr(X), logdet(X)), S, written = function() list(tr(X), logdet(X))),
    negeig_pow = list(function() (-eigmax(X))^0.3, S),
    sqrt_eigmax = list(function() sqrt(eigmax(X)), S),
    sle_exp_inv = list(function() sum_log_eigmax("exp", Inverse(X), 2), S),
    sle_inv = list(function() sum_log_eigmax(Inverse(X), 2), S),
    affine_tr_inv = list(function() affine_map("tr", Inverse(X), B), S),
    affine_diag = list(function() affine_map("diag", X, B), S),
    eigmax_inv = list(function() eigmax(Inverse(X)), S),
    tr_adjoint = list(function() tr(Transpose(X)), S),
    # upstream LinearAlgebra.diag of a symbolic matrix throws while building
    # the expression; the R node is built directly (its rule: GConvex)
    logdet_diag = NULL,
    # logdet(X + B) with a constant matrix B: symcompR adds a numeric matrix
    # to a matrix symbol entrywise, so the case has no R form
    logdet_sum_shift = NULL,
    logdet_XY = list(function() logdet(X + Y), S),
    tr_XY = list(function() tr(X + Y), S),
    scalar_mat = list(function() scalar_mat(X, 3), S),
    quad_canon = list(function() Transpose(p) * X * p, S),
    quad_canon_euclid = list(function() Transpose(p) * X * p, NULL),
    conj_euclid = list(function() conjugation(X, A), NULL),
    abs_eigmax = list(function() abs(eigmax(X)), S),
    abs_eigmax_euclid = list(function() abs(eigmax(X)), NULL),
    neg_tr = list(function() -tr(X), S),
    exp_neg_tr = list(function() exp(-tr(X)), S),
    log_neg_tr = list(function() log(-tr(X)), S),
    XY_mul = list(function() tr(X * Y), S),
    dist_spd_on_lorentz = list(function() distance(S, A, X), L),
    barrier_on_spd = list(function() lorentz_log_barrier(p), S),
    euclid_manifold = list(function() tr(X), Euclidean(3)),
    eigsummax_euclid = list(function() eigsummax(X, 2), NULL),
    inv_euclid = list(function() tr(Inverse(X)), NULL))
}

gd_run <- function(case) {
  w <- character()
  r <- tryCatch(withCallingHandlers(analyze(case[[1L]](), case[[2L]]), warning = function(cnd) {
    w <<- c(w, conditionMessage(cnd))
    invokeRestart("muffleWarning")
  }), error = function(e) e)
  if (inherits(r, "error")) return(list(error = conditionMessage(r)))
  list(curvature = r$curvature, sign = r$sign, gcurvature = r$gcurvature, warnings = w)
}

test_that("the geodesic analysis certifies the upstream test set", {
  cs <- gd_cases()
  g <- function(nm) gd_run(cs[[nm]])$gcurvature
  for (nm in c("logdet_conj_inv", "logdet_tr_inv", "lqf_sum", "brascamp", "tr_conj", "sdiv", "sdiv_sum", "dist_sq",
               "dist_sq_sum", "matsqrt", "tr_inv_logdet", "tr_shift_sq", "lqf_inv", "lqf_ys", "lqf_ys_inv",
               "eigsummax_log", "schatten_log", "exp_eigsummax_log", "sle", "sle_exp", "tr_affine_conj", "hadamard",
               "logdet_affine_hadamard", "tr", "eigmax", "log_tr", "lor_dist", "lor_barrier", "lor_homq", "lor_homd",
               "lor_ls", "lor_nhq", "lor_comp"))
    expect_identical(g(nm), "GConvex", label = nm)
  for (nm in c("sqrt_XY", "eigmin", "sqrt", "norm")) expect_identical(g(nm), "GUnknownCurvature", label = nm)
  expect_identical(g("logdet"), "GLinear")
  expect_false(identical(g("abs_logdet_tr"), "GConvex"))
  expect_identical(gd_run(cs$tr_sign)$sign, "Positive")
  expect_identical(gd_run(cs$eigmax_sign)$sign, "Positive")
  expect_identical(gd_run(cs$tr_sign_euclid)$sign, "AnySign")
  for (nm in c("logdet", "lqf_sign", "sle_sign", "lor_barrier", "lor_homq_neg", "lor_homd_neg"))
    expect_false(identical(gd_run(cs[[nm]])$sign, "Positive"), label = nm)
  expect_null(analyze(tr(gd_X))$gcurvature)
  expect_error(analyze(tr(gd_X), Euclidean(3)), "Only SymmetricPositiveDefinite and Lorentz manifolds")
})

test_that("add_gdcprule registers an atom", {
  add_gdcprule("gd_test_atom", "Lorentz", "Positive", "GConvex", "GIncreasing")
  r <- analyze(Function("gd_test_atom")(gd_p), Lorentz(2))
  expect_identical(r$gcurvature, "GConvex")
  expect_identical(r$curvature, "UnknownCurvature")
})

test_that("the geodesic atoms compute their values on numbers", {
  A <- gd_A; B <- gd_B
  expect_equal(conjugation(A, B), t(B) %*% A %*% B)
  expect_equal(tr(A), 6.5)
  expect_equal(scalar_mat(A, 2), diag(6.5, 2))
  ld <- function(M) as.numeric(determinant(M)$modulus)
  expect_equal(sdivergence(A, B), ld((A + B) / 2) - ld(A %*% B) / 2)
  e <- eigen(A, symmetric = TRUE)
  Ai <- e$vectors %*% diag(1 / sqrt(e$values)) %*% t(e$vectors)
  expect_equal(distance(gd_S, A, B), sqrt(sum(log(eigen(Ai %*% B %*% Ai, symmetric = TRUE)$values)^2)))
  expect_equal(distance(gd_S, A, A), 0)
  expect_equal(distance(gd_L, c(0, 0, 1), c(1, 0, 1)), 1)
  expect_error(distance(gd_L, c(0, 0, 1), c(0, 0, 2)), "DomainError")
  expect_equal(log_quad_form(c(1, 2, 0), A), log(sum(c(1, 2, 0) * (A %*% c(1, 2, 0)))))
  ev <- sort(eigen(A, symmetric = TRUE)$values)
  expect_equal(eigsummax(A, 2), sum(ev[2:3]))
  expect_equal(eigsummin(A, 1), ev[1])
  expect_error(eigsummax(A, 4), "k must be between 1 and size")
  expect_equal(schatten_norm(A, 2), sqrt(sum(ev^2)))
  expect_equal(sum_log_eigmax(A, 2), sum(log(ev[2:3])))
  expect_equal(sum_log_eigmax("exp", A, 2), sum(ev[2:3]))
  expect_equal(affine_map("conjugation", A, B, gd_C), B + conjugation(A, gd_C))
  expect_error(affine_map("conjugation", A, -B, gd_C), "B must be positive semi-definite")
  expect_equal(hadamard_product(A, B), A * B)
  expect_equal(affine_map("hadamard_product", A, B, gd_C), gd_C + A * B)
  expect_equal(lorentz_log_barrier(c(0, 0, 3)), -log(2))
  expect_equal(lorentz_homogeneous_quadratic(diag(c(2, 2, 1)), c(1, 2, 3)), 19)
  expect_error(lorentz_homogeneous_quadratic(diag(c(1, 1, -2)), c(1, 2, 3)), "geodesic convexity conditions")
  expect_equal(lorentz_homogeneous_diagonal(c(2, 2, 1), c(1, 2, 3)), 19)
  expect_error(lorentz_homogeneous_diagonal(c(1, 1, -2), c(1, 2, 3)), "is required")
  expect_equal(lorentz_least_squares(diag(3), c(0, 0, -1), c(1, 0, 2)), 1 + 0 + 9)
  expect_error(lorentz_nonhomogeneous_quadratic(diag(3), c(1, 0, 0), 0, c(1, 0, 2)), "Lorentz cone")
  ch <- 1.2; sh <- sqrt(ch^2 - 1)
  O <- matrix(c(1, 0, 0, 0, ch, -sh, 0, -sh, ch), 3)
  expect_equal(lorentz_transform(O, c(0, 0, 1)), as.numeric(O %*% c(0, 0, 1)))
  expect_error(lorentz_transform(diag(c(1, 1, 2)), c(0, 0, 1)), "not in the Lorentz group")
})
)---"

refblock <- if (length(refs)) c("", "gd_ref <- list(", paste(refs, collapse = ",\n"), ")", "",
  r"---(test_that("the geodesic analysis matches SymbolicAnalysis.jl", {
  cs <- gd_cases()
  for (nm in names(gd_ref)) {
    if (is.null(cs[[nm]])) next
    w <- cs[[nm]]$written
    if (!is.null(w) && !identical(.keys(.args(cs[[nm]][[1L]]())), .keys(w()))) next
    want <- gd_ref[[nm]]
    got <- gd_run(cs[[nm]])
    if (!is.null(want$error)) {
      expect_identical(got$error, want$error, label = paste(nm, "error"))
      next
    }
    expect_identical(got$curvature, want$curvature, label = paste(nm, "curvature"))
    expect_identical(got$sign, want$sign, label = paste(nm, "sign"))
    expect_identical(got$gcurvature, want$gcurvature, label = paste(nm, "gcurvature"))
    expect_identical(got$warnings, want$warnings, label = paste(nm, "warnings"))
  }
}))---") else character()

writeLines(c(header, static, refblock), out)

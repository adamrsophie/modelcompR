# Writes tests/testthat/test-stabilized-irk.R from the output of
# tools/irkc-probe.jl:
#   REF=irkc.tsv OUT=tests/testthat/test-stabilized-irk.R Rscript tools/irkc-gen-test.R
# The IRKC cases whose first step is rejected or that apply an event (p2 = 5
# plain, cb and eig; p2 = 40 cb) differ from OrdinaryDiffEq on purpose, since
# OrdinaryDiffEq keeps f1 and f2 of the last attempt (see PORTING.md); they
# are tested for accuracy instead.
ref <- read.delim(Sys.getenv("REF"), header = FALSE, stringsAsFactors = FALSE)
differs <- ref[, 1] == "IRKC" & ((ref[, 2] == 5 & ref[, 4] %in% c("plain", "cb", "eig")) |
                                   (ref[, 2] == 40 & ref[, 4] == "cb"))
row <- function(k) {
  u <- as.numeric(strsplit(ref[k, 12], ",")[[1]])
  sprintf(paste0("  list(alg = \"%s\", a = %s, b = %s, case = \"%s\", n = %dL, nf = %dL, nf2 = %dL, njacs = %dL,\n",
                 "       nw = %dL, nsolve = %dL, nreject = %dL, u = c(%s))"),
          ref[k, 1], format(ref[k, 2]), format(ref[k, 3]), ref[k, 4], ref[k, 5], ref[k, 6], ref[k, 7], ref[k, 8],
          ref[k, 9], ref[k, 10], ref[k, 11], paste(sprintf("%.17g", u), collapse = ", "))
}
irkc <- which(ref[, 1] == "IRKC" & !differs)
dae <- which(ref[, 1] == "DImplicitEuler")
out <- c(
"# Reference values from OrdinaryDiffEq (OrdinaryDiffEqStabilizedIRK,",
"# OrdinaryDiffEqBDF), generated by tools/irkc-probe.jl and",
"# tools/irkc-gen-test.R: steps, evaluations of f1 and f2, Jacobians,",
"# factorizations, linear solves, rejections and the final state.",
"",
"irkc_n <- 8",
"irkc_f1 <- function(u, p, t) {",
"  l <- c(0, u[-irkc_n]); r <- c(u[-1], 0)",
"  p[1] * (l - 2 * u + r) * (irkc_n + 1)^2 - 0.5 * (u * u * u)",
"}",
"irkc_f2 <- function(u, p, t) p[2] * u * (1 - u) + 0.1 * t",
"irkc_j1 <- function(u, p, t) {",
"  J <- matrix(0, irkc_n, irkc_n)",
"  for (i in seq_len(irkc_n)) {",
"    J[i, i] <- -2 * p[1] * (irkc_n + 1)^2 - 1.5 * u[i]^2",
"    if (i > 1) J[i, i - 1] <- p[1] * (irkc_n + 1)^2",
"    if (i < irkc_n) J[i, i + 1] <- p[1] * (irkc_n + 1)^2",
"  }",
"  J",
"}",
"irkc_u0 <- seq_len(irkc_n) * (irkc_n + 1 - seq_len(irkc_n)) / irkc_n^2",
"irkc_cb <- DiscreteCallback(function(u, t, integ) t == 0.1, function(integ) integ$u <- integ$u * 0.5)",
"irkc_prob <- function(b) {",
"  SplitODEProblem(SplitFunction(irkc_f1, irkc_f2, jac = irkc_j1), irkc_u0, c(0, 0.3),",
"                  if (b == 5) c(1, 5) else c(0.2, 40))",
"}",
"irkc_solve <- function(case, b, rt) {",
"  prob <- irkc_prob(b)",
"  switch(case,",
"    plain = solve(prob, IRKC(), reltol = rt, abstol = 1e-6),",
"    tstop = solve(prob, IRKC(), reltol = rt, abstol = 1e-6, tstops = 0.1),",
"    cb = solve(prob, IRKC(), reltol = rt, abstol = 1e-6, tstops = 0.1, callback = irkc_cb),",
"    eig = solve(prob, IRKC(eigen_est = 30), reltol = rt, abstol = 1e-6),",
"    fixed = solve(prob, IRKC(), dt = 1 / 32, adaptive = FALSE))",
"}",
"irkc_cases <- list(",
paste0(vapply(irkc, row, ""), collapse = ",\n"),
")",
"dae_cases <- list(",
paste0(vapply(dae, row, ""), collapse = ",\n"),
")",
"",
"irkc_check <- function(sol, r) {",
"  lab <- paste(r$alg, r$a, r$case)",
"  st <- sol$stats",
"  expect_equal(length(sol$t), r$n, label = lab)",
"  expect_equal(c(st$nf, st$nf2, st$njacs, st$nw, st$nsolve, st$nreject),",
"               c(r$nf, r$nf2, r$njacs, r$nw, r$nsolve, r$nreject), label = lab)",
"  expect_equal(sol$u[[length(sol$u)]], r$u, tolerance = 1e-10, ignore_attr = TRUE, label = lab)",
"}",
"",
"test_that(\"IRKC follows OrdinaryDiffEqStabilizedIRK\", {",
"  for (r in irkc_cases) irkc_check(irkc_solve(r$case, r$a, r$b), r)",
"})",
"",
"test_that(\"IRKC evaluates f1 and f2 at the start of a step after a rejection or an event\", {",
"  # OrdinaryDiffEq reuses the values of the rejected attempt, with errors of",
"  # 0.08 and 0.10 here; the reference is a tight Rodas5P solution",
"  full <- ODEProblem(function(u, p, t) irkc_f1(u, p, t) + irkc_f2(u, p, t), irkc_u0, c(0, 0.3), c(1, 5))",
"  for (case in c(\"plain\", \"cb\")) {",
"    sol <- irkc_solve(case, 5, 1e-4)",
"    acc <- if (case == \"cb\") solve(full, Rodas5P(), reltol = 1e-11, abstol = 1e-13, tstops = 0.1, callback = irkc_cb)",
"      else solve(full, Rodas5P(), reltol = 1e-11, abstol = 1e-13)",
"    expect_lt(max(abs(sol$u[[length(sol$u)]] - acc$u[[length(acc$u)]])), 0.01)",
"  }",
"  expect_error(solve(ODEProblem(function(u, p, t) -u, 1, c(0, 1)), IRKC()), \"SplitODEProblem\")",
"})",
"",
"test_that(\"DImplicitEuler follows OrdinaryDiffEqBDF with an analytic DAE Jacobian\", {",
"  F <- function(du, u, p, t) c(du[1] - u[2], u[2] * u[2] * u[2] + u[2] + u[1] * u[1] * u[1] + u[1])",
"  J <- function(du, u, p, gamma, t) matrix(c(gamma, 3 * u[1]^2 + 1, -1, 3 * u[2]^2 + 1), 2)",
"  prob <- DAEProblem(DAEFunction(F, jac = J), c(-1, -1), c(1, -1), c(0, 2), differential_vars = c(TRUE, FALSE))",
"  for (r in dae_cases) {",
"    irkc_check(solve(prob, DImplicitEuler(), reltol = r$a, abstol = r$b, initializealg = NoInit()), r)",
"  }",
"})")
writeLines(out, Sys.getenv("OUT"))

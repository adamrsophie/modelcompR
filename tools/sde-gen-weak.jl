# Writes the constants of the weak SDE methods (the *ConstantCache(T, T2)
# constructors of StochasticDiffEqWeak/src/caches/srk_weak_caches.jl) as an
# R list, for R/stochastic-weak.R.
#
# Run from the repository root:
#   julia --project=tools/julia tools/sde-gen-weak.jl R/stochastic-weak-constants.R
using StochasticDiffEq
const W = Base.loaded_modules[Base.PkgId(Base.UUID("af2a2fcd-1c36-4cbe-a6d0-5afda784a085"), "StochasticDiffEqWeak")]
num(x) = x == 0 ? "0" : repr(Float64(x))
caches = [:DRI1ConstantCache, :RI1ConstantCache, :RI3ConstantCache, :RI5ConstantCache, :RI6ConstantCache,
          :RDI1WMConstantCache, :RDI2WMConstantCache, :RDI3WMConstantCache, :RDI4WMConstantCache,
          :RS1ConstantCache, :RS2ConstantCache, :SIEAConstantCache, :SIEBConstantCache, :SMEAConstantCache,
          :SMEBConstantCache, :W2Ito1ConstantCache, :NONConstantCache, :COMConstantCache, :NON2ConstantCache]
open(ARGS[1], "w") do io
    println(io, "# Generated by tools/sde-gen-weak.jl; do not edit.")
    println(io, "# Constants of the weak stochastic Runge-Kutta methods, from the")
    println(io, "# *ConstantCache constructors of StochasticDiffEqWeak.")
    println(io)
    println(io, ".WEAK_CONSTANTS <- list(")
    out = String[]
    for c in caches
        cc = try getfield(W, c)(Float64, Float64) catch; getfield(W, c)(Float64) end
        fields = String[]
        for fn in fieldnames(typeof(cc))
            v = getfield(cc, fn)
            v isa Real || continue
            name = replace(string(fn), "α" => "alpha", "β" => "beta", "γ" => "gamma", "λ" => "lambda", "μ" => "mu", "µ" => "mu", "ν" => "nu", "δ" => "delta")
            push!(fields, "    $(name) = $(num(v))")
        end
        push!(out, "  " * replace(string(c), "ConstantCache" => "") * " = list(\n" * join(fields, ",\n") * "\n  )")
        println(stderr, "OK ", c, " ", nameof(typeof(cc)))
    end
    println(io, join(out, ",\n"))
    println(io, ")")
end

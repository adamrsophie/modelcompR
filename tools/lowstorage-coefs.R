# Writes R/solvers-lowstorage-tableaus.R from the ConstantCache fields of the
# OrdinaryDiffEqLowStorageRK methods dumped by tools/lowstorage-probe.jl.
#
#   Rscript tools/lowstorage-coefs.R caches.tsv R/solvers-lowstorage-tableaus.R
#
# The coefficients are kept as the hexadecimal floating point literals of the
# Julia caches, and the Unicode field names get ASCII names.

args <- commandArgs(trailingOnly = TRUE)
rows <- strsplit(readLines(args[1], encoding = "UTF-8"), "\t", fixed = TRUE)

ascii_name <- function(x) {
  map <- c("γ" = "gamma", "δ" = "delta", "β" = "beta", "α" = "alpha",
           "B̂ₗ" = "Bhl", "B̂ᵢ" = "Bhi", "Aᵢ" = "Ai", "Bₗ" = "Bl",
           "Bᵢ" = "Bi", "Cᵢ" = "Ci", "₁" = "1", "₂" = "2", "₃" = "3",
           "₄" = "4")
  for (k in names(map)) x <- gsub(k, map[[k]], x, fixed = TRUE)
  if (grepl("[^ -~]", x)) stop("unmapped field name ", x)
  x
}

wrap <- function(vals, indent) {
  out <- character()
  line <- ""
  for (v in vals) {
    piece <- if (nzchar(line)) paste0(line, ", ", v) else v
    if (nchar(piece) > 92L && nzchar(line)) {
      out <- c(out, paste0(line, ","))
      line <- v
    } else line <- piece
  }
  c(out, line)
}

out <- c("# Generated by tools/lowstorage-coefs.R from the ConstantCache fields of",
         "# OrdinaryDiffEqLowStorageRK (tools/lowstorage-probe.jl); do not edit by hand.",
         "# Each entry gives the cache family and its coefficients for .lsrk_step().",
         "",
         ".LSRK <- list(")
entries <- character()
for (r in rows) {
  fields <- r[-(1:6)]
  body <- paste0("    family = \"", r[2], "\"")
  for (fl in fields) {
    kv <- strsplit(fl, "=", fixed = TRUE)[[1]]
    nm <- ascii_name(kv[1])
    if (nm == "step") next
    vals <- strsplit(kv[2], ",", fixed = TRUE)[[1]]
    if (length(vals) == 1L) {
      body <- c(body, paste0("    ", nm, " = ", vals))
    } else {
      w <- wrap(vals, 6L)
      w[1] <- paste0("    ", nm, " = c(", w[1])
      if (length(w) > 1L) w[-1] <- paste0("      ", w[-1])
      w[length(w)] <- paste0(w[length(w)], ")")
      body <- c(body, w)
    }
  }
  # join the fields with commas at the ends of their last lines
  starts <- grep("^    [A-Za-z]", body)
  ends <- c(starts[-1] - 1L)
  body[ends] <- paste0(body[ends], ",")
  entries <- c(entries, paste0("  ", r[1], " = list("), body, "  ),")
}
entries[length(entries)] <- "  )"
writeLines(c(out, entries, ")"), args[2])

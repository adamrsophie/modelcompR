# Writes R/solvers-rkn-tableaus.R: the coefficients of the symplectic
# methods of OrdinaryDiffEqSymplecticRK (symplectic_tableaus.jl) and of the
# Runge-Kutta-Nystrom methods of OrdinaryDiffEqRKN (rkn_tableaus.jl), as
# built by the Julia constructors for Float64, written as exact hexadecimal
# float literals (R's decimal parser can be one ulp off for 17 digits).
#
# Run from the repository root:
#   julia --project=tools/julia tools/rkn-dump.jl R/solvers-rkn-tableaus.R
using OrdinaryDiffEqSymplecticRK, OrdinaryDiffEqRKN, Printf
const S = OrdinaryDiffEqSymplecticRK
const N = OrdinaryDiffEqRKN
const T = Float64

hx(x) = (x = Float64(x); x == 0 ? "0" : @sprintf("%a", x))
rv(v) = "c(" * join(hx.(collect(v)), ", ") * ")"
rmat(m) = "matrix(c(" * join(hx.(vec(m)), ", ") * "), $(size(m, 1)), $(size(m, 2)))"
rvec(v) = isempty(v) ? "numeric()" : rv(v)

const SYMP = (:PseudoVerletLeapfrog, :McAte2, :Ruth3, :McAte3, :CandyRoz4, :McAte4, :CalvoSanz4, :McAte42,
              :McAte5, :Yoshida6, :KahanLi6, :McAte8, :KahanLi8, :SofSpa10)
const VI = (:Nystrom4VelocityIndependent, :Nystrom5VelocityIndependent, :DPRKN4, :DPRKN5, :DPRKN6, :DPRKN6FM,
            :DPRKN8, :DPRKN12, :ERKN4, :ERKN5, :ERKN7)
const VD = (:Nystrom4, :FineRKN4, :FineRKN5, :RKN4)

open(ARGS[1], "w") do io
    println(io, "# Generated by tools/rkn-dump.jl from OrdinaryDiffEqSymplecticRK")
    println(io, "# (symplectic_tableaus.jl) and OrdinaryDiffEqRKN (rkn_tableaus.jl); do not edit.")
    println(io, "# Coefficients are exact hexadecimal floats.")
    println(io)
    println(io, "# Drift (b) and kick (a) coefficients of the symplectic composition methods.")
    println(io, ".SYMP_TABLEAUS <- list(")
    rows = String[]
    for nm in SYMP
        tab = getfield(S, Symbol(nm, :ConstantCache))(T, T)
        push!(rows, "  $nm = list(a = $(rv(tab.a)), b = $(rv(tab.b)))")
    end
    println(io, join(rows, ",\n"))
    println(io, ")")
    println(io)
    println(io, "# Nystrom tableaus: a (position coupling), abar (velocity coupling of the")
    println(io, "# velocity dependent methods), b, bp, btilde, bptilde and the nodes c of")
    println(io, "# stages 2 to s; DPRKN6 also has its dense output polynomials R and Rp.")
    println(io, ".RKN_TABLEAUS <- list(")
    rows = String[]
    for nm in VI
        tab = getfield(N, Symbol(nm, :Tableau))(T, T)
        s = "  $nm = list(type = \"VI\", a = $(rmat(tab.a)), b = $(rv(tab.b)), bp = $(rv(tab.bp)),\n" *
            "    btilde = $(rvec(tab.btilde)), bptilde = $(rvec(tab.bptilde)), c = $(rv(tab.c)),\n" *
            "    pos_only_error = $(tab.pos_only_error ? "TRUE" : "FALSE")"
        if hasproperty(tab, :R)
            s *= ",\n    R = $(rmat(tab.R)), Rp = $(rmat(tab.Rp))"
        end
        push!(rows, s * ")")
    end
    for nm in VD
        tab = getfield(N, Symbol(nm, :Tableau))(T, T)
        push!(rows, "  $nm = list(type = \"VD\", a = $(rmat(tab.a)), abar = $(rmat(tab.abar)), b = $(rv(tab.b)),\n" *
                    "    bp = $(rv(tab.bp)), btilde = $(rvec(tab.btilde)), bptilde = $(rvec(tab.bptilde)),\n" *
                    "    c = $(rv(tab.c)), nf_per_step = $(tab.nf_per_step)L)")
    end
    c3 = N.IRKN3ConstantCache(T, T)
    push!(rows, "  IRKN3 = list(" * join(["$f = $(hx(getfield(c3, f)))" for f in fieldnames(typeof(c3))], ", ") * ")")
    c4 = N.IRKN4ConstantCache(T, T)
    f4 = [f for f in fieldnames(typeof(c4)) if getfield(c4, f) isa Real]
    push!(rows, "  IRKN4 = list(" * join(["$f = $(hx(getfield(c4, f)))" for f in f4], ", ") * ")")
    println(io, join(rows, ",\n"))
    println(io, ")")
end

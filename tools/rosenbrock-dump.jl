lit(x) = (x = Float64(x); x == 0 ? "0" : repr(x))
rvec(v) = isempty(v) ? "numeric()" : "c(" * join(lit.(collect(v)), ", ") * ")"
function rmat(m)
    r, c = size(m)
    r == 0 && return "matrix(numeric(), nrow = 0L, ncol = $(c)L)"
    rows = [join(lit.(m[i, :]), ", ") for i in 1:r]
    return "matrix(c(\n      " * join(rows, ",\n      ") * "),\n    nrow = $(r)L, ncol = $(c)L, byrow = TRUE)"
end


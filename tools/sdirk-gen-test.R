# Writes tests/testthat/test-sdirk.R from the output of tools/sdirk-probe.jl
# (ERROR lines are skipped). From the repository root:
#   julia --project=tools/julia tools/sdirk-probe.jl > sdirk.tsv
#   Rscript tools/sdirk-gen-test.R sdirk.tsv tests/testthat/test-sdirk.R
args <- commandArgs(TRUE)
ref <- read.delim(args[1], header = FALSE, stringsAsFactors = FALSE, quote = "")
ref <- ref[ref[, 3] != "ERROR", ]
hermite <- grepl("_(MaxOrder|VariableOrder|CutoffOrder)$", ref[, 1])
fmt <- function(k) {
  u <- as.numeric(strsplit(ref[k, 11], ",")[[1]])
  m <- as.numeric(strsplit(ref[k, 12], ",")[[1]])
  sprintf("  list(\"%s\", \"%s\", c(%s),\n       c(%s),\n       c(%s))", ref[k, 1], ref[k, 2],
          paste0(as.integer(ref[k, 3:10]), "L", collapse = ", "),
          paste(sprintf("%.17g", u), collapse = ", "), paste(sprintf("%.17g", m), collapse = ", "))
}
block <- function(name, rows) c(paste0(name, " <- list("), paste(vapply(rows, fmt, ""), collapse = ",\n"), ")")
out <- c(
"# Reference values from OrdinaryDiffEqSDIRK, out of place (tools/sdirk-probe.jl):",
"# a nonlinear heat equation, the same equation split into a stiff part f1",
"# and a reaction part f2 for the IMEX methods, and the Robertson problem",
"# in mass matrix form, all with analytic Jacobians. Each case holds the",
"# saved points, nf, nf2, njacs, nw, nsolve, naccept and nreject, the final",
"# state and the dense output at t = 0.123. The _nlk, _nlpred and _nlnodiv",
"# cases pass NLNewton settings, a stage predictor and check_div = FALSE as",
"# the nlsolve keyword.",
"",
"sd_n <- 8",
"sd_heat <- function(u, p, t) {",
"  l <- c(0, u[-sd_n]); r <- c(u[-1], 0)",
"  p[1] * (l - 2 * u + r) * (sd_n + 1)^2 - 0.5 * (u * u * u) + 0.1 * t",
"}",
"sd_f1 <- function(u, p, t) {",
"  l <- c(0, u[-sd_n]); r <- c(u[-1], 0)",
"  p[1] * (l - 2 * u + r) * (sd_n + 1)^2 - 0.5 * u * u * u",
"}",
"sd_f2 <- function(u, p, t) p[2] * u * (1 - u) + 0.1 * t",
"sd_jac <- function(u, p, t) {",
"  J <- matrix(0, sd_n, sd_n)",
"  for (i in seq_len(sd_n)) {",
"    J[i, i] <- -2 * p[1] * (sd_n + 1)^2 - 1.5 * u[i]^2",
"    if (i > 1) J[i, i - 1] <- p[1] * (sd_n + 1)^2",
"    if (i < sd_n) J[i, i + 1] <- p[1] * (sd_n + 1)^2",
"  }",
"  J",
"}",
"sd_rober <- function(u, p, t)",
"  c(-0.04 * u[1] + 1.0e4 * u[2] * u[3], 0.04 * u[1] - 1.0e4 * u[2] * u[3] - 3.0e7 * u[2] * u[2], u[1] + u[2] + u[3] - 1)",
"sd_rjac <- function(u, p, t)",
"  matrix(c(-0.04, 1.0e4 * u[3], 1.0e4 * u[2], 0.04, -1.0e4 * u[3] - 6.0e7 * u[2], -1.0e4 * u[2], 1, 1, 1), 3, 3, byrow = TRUE)",
"sd_u0 <- seq_len(sd_n) * (sd_n + 1 - seq_len(sd_n)) / sd_n^2",
"sd_prob <- ODEProblem(ODEFunction(sd_heat, jac_fn = sd_jac), sd_u0, c(0, 0.3), 1)",
"sd_sprob <- SplitODEProblem(SplitFunction(sd_f1, sd_f2, jac = sd_jac), sd_u0, c(0, 0.3), c(1, 5))",
"sd_mprob <- ODEProblem(ODEFunction(sd_rober, jac_fn = sd_rjac), c(1, 0, 0), c(0, 0.5), mass_matrix = diag(c(1, 1, 0)))",
"sd_cb <- DiscreteCallback(function(u, t, integ) t == 0.1, function(integ) integ$u <- integ$u * 0.5)",
"sd_lim <- function(u, integ, p, t) u",
"sd_pred <- function(uprev, p, t, dt) uprev * (1 - 0.1 * dt) + 0.01 * t",
"",
"# label: [split_ | mm_] method [_option]",
"sd_setup <- function(label) {",
"  pr <- sd_prob",
"  if (startsWith(label, \"split_\")) { pr <- sd_sprob; label <- sub(\"^split_\", \"\", label) }",
"  if (startsWith(label, \"mm_\")) { pr <- sd_mprob; label <- sub(\"^mm_\", \"\", label) }",
"  if (label == \"Cash4_e2\") return(list(pr, Cash4(embedding = 2)))",
"  parts <- strsplit(label, \"_\", fixed = TRUE)[[1]]",
"  f <- get(parts[1])",
"  alg <- if (length(parts) == 1) f() else switch(parts[2],",
"    nosmooth = f(smooth_est = FALSE), smooth = f(smooth_est = TRUE), limiter = f(step_limiter = sd_lim),",
"    nlk = f(nlsolve = NLNewton(kappa = 1e-3, max_iter = 4L, new_W_dt_cutoff = 0.5)),",
"    nlpred = f(nlsolve = NLNewton(predictor = sd_pred)), nlnodiv = f(nlsolve = NLNewton(check_div = FALSE)),",
"    f(predictor = Predictor[[parts[2]]]))",
"  list(pr, alg)",
"}",
"sd_solve <- function(pr, alg, case) switch(case,",
"  plain = solve(pr, alg, reltol = 1e-4, abstol = 1e-6),",
"  loose = solve(pr, alg, reltol = 1e-2, abstol = 1e-4),",
"  tstop = solve(pr, alg, reltol = 1e-4, abstol = 1e-6, tstops = 0.1),",
"  cb = solve(pr, alg, reltol = 1e-4, abstol = 1e-6, tstops = 0.1, callback = sd_cb),",
"  fixed = solve(pr, alg, dt = 1 / 32, adaptive = FALSE),",
"  fixedcb = solve(pr, alg, dt = 1 / 32, adaptive = FALSE, tstops = 0.1, callback = sd_cb),",
"  mm = solve(pr, alg, reltol = 1e-4, abstol = 1e-6, initializealg = NoInit()),",
"  mmfixed = solve(pr, alg, dt = 1 / 64, adaptive = FALSE, initializealg = NoInit()))",
"sd_check <- function(r) {",
"  x <- sd_setup(r[[1]])",
"  sol <- sd_solve(x[[1]], x[[2]], r[[2]])",
"  st <- sol$stats",
"  lab <- paste(r[[1]], r[[2]])",
"  expect_equal(c(length(sol$t), st$nf, st$nf2, st$njacs, st$nw, st$nsolve, st$naccept, st$nreject), r[[3]],",
"               label = lab)",
"  expect_equal(sol$u[[length(sol$u)]], r[[4]], tolerance = 1e-12, ignore_attr = TRUE, label = lab)",
"  expect_equal(as.numeric(sol(0.123)), r[[5]], tolerance = 1e-12, label = lab)",
"}",
"",
block("sd_cases", which(!hermite)),
"",
"test_that(\"the SDIRK, ESDIRK and IMEX methods follow OrdinaryDiffEqSDIRK\", {",
"  for (r in sd_cases) sd_check(r)",
"})",
"",
"test_that(\"the interpolant predictors solve the same problem\", {",
"  ref <- solve(sd_prob, Kvaerno4(), reltol = 1e-8, abstol = 1e-10)",
"  for (pr in c(\"MaxOrder\", \"VariableOrder\", \"CutoffOrder\")) {",
"    sol <- solve(sd_prob, Kvaerno4(predictor = Predictor[[pr]]), reltol = 1e-4, abstol = 1e-6)",
"    expect_equal(sol$retcode, \"Success\")",
"    expect_equal(sol$u[[length(sol$u)]], ref$u[[length(ref$u)]], tolerance = 1e-2)",
"  }",
"})",
"",
"test_that(\"SDIRK constructors check their options\", {",
"  expect_s3_class(SDIRK22(), \"Trapezoid\")",
"  expect_identical(SDIRK22()$step, Trapezoid()$step)",
"  expect_error(TRBDF2(predictor = \"Quadratic\"), \"Predictor\")",
"  expect_warning(a <- Kvaerno4(extrapolant = \"interpolant\"), \"deprecated\")",
"  expect_identical(environment(a$init)$spec$predictor, Predictor$MaxOrder)",
"  expect_warning(Kvaerno4(extrapolant = \"constant\"), \"deprecated\")",
"  expect_error(KenCarp4(step_limiter = 1), \"function\")",
"  expect_error(solve(sd_prob, SFSDIRK4()), \"give dt\")",
"  mprob <- ODEProblem(sd_rober, c(1, 0, 0), c(0, 0.1), mass_matrix = matrix(c(1, 1, 0, 0, 1, 0, 0, 0, 0), 3))",
"  expect_error(solve(mprob, KenCarp4()), \"diagonal mass matrices\")",
"})")
if (any(hermite)) {
  i <- which(out == "test_that(\"the interpolant predictors solve the same problem\", {")
  out <- append(out, c("# The MaxOrder, VariableOrder and CutoffOrder predictors extrapolate the",
"# dense output of the last step. OrdinaryDiffEqSDIRK takes its start",
"# value from integrator.uprev2, which only alg_extrapolates methods update",
"# (it stays u0), and its derivatives from integrator.k, which a rejected",
"# step overwrites. R uses the last accepted step; with both stale values",
"# put back the steps agree with OrdinaryDiffEq.",
    block("sd_hermite_cases", which(hermite)), "",
"test_that(\"the interpolant predictors match OrdinaryDiffEqSDIRK with its stale step history\", {",
"  stale <- function(ctx, cache) list(y0 = sd_u0, k = cache$k_last)",
"  local_mocked_bindings(.sdirk_history = stale, .package = \"modelcompR\")",
"  for (r in sd_hermite_cases) sd_check(r)",
"})",
""), after = i - 1L)
}
writeLines(out, args[2])

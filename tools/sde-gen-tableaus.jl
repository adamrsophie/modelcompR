# Writes R/stochastic-tableaus.R: the tableaus of the Roessler SRI and SRA
# methods (StochasticDiffEqHighOrder/src/tableaus.jl), the stochastic KenCarp
# tableaus and the weak methods' tableaus (StochasticDiffEqWeak/src/tableaus.jl),
# evaluated by their Julia constructors.
#
# Run from the repository root:
#   julia --project=tools/julia tools/sde-gen-tableaus.jl
using StochasticDiffEq
const SDE = StochasticDiffEq
num(x) = x == 0 ? "0" : repr(Float64(x))
function rval(x)
    if x isa AbstractMatrix
        return "matrix(c(" * join(num.(vec(x)), ", ") * "), $(size(x, 1)), $(size(x, 2)))"
    elseif x isa AbstractVector
        return "c(" * join(num.(x), ", ") * ")"
    elseif x isa Rational || x isa Real
        return num(x)
    else
        return nothing
    end
end
ctors = [:constructSRIW1, :constructSRIW2, :constructSRIOpt1, :constructSRIOpt2, :constructSRA1, :constructSRA2,
         :constructSRA3, :constructSOSRA, :constructSOSRA2, :constructSKenCarp, :constructExplicitSKenCarp,
         :constructDRI1, :constructRI1, :constructRI3, :constructRI5, :constructRI6, :constructRDI1WM,
         :constructRDI2WM, :constructRDI3WM, :constructRDI4WM, :constructRS1, :constructRS2, :constructNON,
         :constructNON2]
open("R/stochastic-tableaus.R", "w") do io
    println(io, "# Generated by tools/sde-gen-tableaus.jl; do not edit.")
    println(io, "# Tableaus of the Roessler SRI and SRA methods, the stochastic KenCarp")
    println(io, "# methods and the weak Roessler, Debrabant-Roessler and Komori methods,")
    println(io, "# from their constructors in StochasticDiffEqHighOrder, StochasticDiffEqImplicit")
    println(io, "# and StochasticDiffEqWeak. Field names follow the Julia structs (with")
    println(io, "# subscripts spelled out).")
    println(io)
    println(io, ".SDE_TABLEAUS <- list(")
    first = true
    for c in ctors
        isdefined(SDE, c) || (println(stderr, "missing ", c); continue)
        tab = getfield(SDE, c)()
        fields = String[]
        for fn in fieldnames(typeof(tab))
            v = rval(getfield(tab, fn))
            v === nothing && continue
            name = replace(string(fn), "₀" => "0", "₁" => "1", "₂" => "2", "₃" => "3", "₄" => "4", "₅" => "5",
                           "α" => "alpha", "β" => "beta", "γ" => "gamma", "δ" => "delta", "̃" => "tilde")
            push!(fields, "    $(name) = $(v)")
        end
        first || println(io, ",")
        first = false
        print(io, "  ", replace(string(c), "construct" => ""), " = list(\n", join(fields, ",\n"), "\n  )")
        println(stderr, "OK ", c, " ", typeof(tab).name.name)
    end
    println(io, "\n)")
end
